#!/usr/bin/env python3
"""Generate TS interfaces + embedded schemas from shared/contracts/schema."""
from __future__ import annotations
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCHEMA_DIR = ROOT / "shared/contracts/schema"
OUT = ROOT / "shared/contracts/ts/contracts.ts"
TYPE_MAP = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean"}

def ts_type(prop: dict) -> str:
    if "$ref" in prop:
        return "unknown"
    if "enum" in prop and all(isinstance(item, str) for item in prop["enum"]):
        return " | ".join(f'"{item}"' for item in prop["enum"])
    kind = prop.get("type")
    if isinstance(kind, list):
        parts = [TYPE_MAP.get(item, "unknown") for item in kind]
        return " | ".join(dict.fromkeys(parts))
    if kind == "array":
        return f"Array<{ts_type(prop.get('items', {}))}>"
    if isinstance(kind, str):
        return TYPE_MAP.get(kind, "unknown")
    return "unknown"

def gen(name: str, schema: dict) -> tuple[str, str]:
    iface = "".join(c.upper() if i == 0 else c for i, c in enumerate(name.replace("-", " ").split())) if False else name
    title = schema.get("title", name)
    required = set(schema.get("required", []))
    lines = [f"export interface {title} {{"]
    for key, prop in schema.get("properties", {}).items():
        opt = "" if key in required else "?"
        lines.append(f"  {key}{opt}: {ts_type(prop)};")
    lines.append("}")
    return title, "\n".join(lines)

def main() -> int:
    files = sorted(SCHEMA_DIR.glob("*.json"))
    if not files:
        print("no schemas", file=sys.stderr); return 1
    interfaces, schemas = [], []
    for path in files:
        schema = json.loads(path.read_text())
        key = path.stem.replace("-", "_")
        title = schema.get("title") or key
        _, iface = gen(key, schema)
        interfaces.append(iface)
        schemas.append(f"export const {key}Schema = {json.dumps(schema, ensure_ascii=False, separators=(',', ':'))} as const;")
    out = "// @generated by scripts/schema-ts.py -- do not edit\n\n" + "\n\n".join(interfaces) + "\n\n" + "\n\n".join(schemas) + "\n"
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != out:
            print("schema-ts: out of date; run scripts/schema-ts.py", file=sys.stderr); return 1
        print("schema-ts: up to date"); return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(out)
    print(f"schema-ts: wrote {OUT.relative_to(ROOT)} ({len(files)} schemas)")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
