#!/usr/bin/env python3
"""Minimal `zk compose` for the POC: profile -> generated glue crate.

Real `zk` (see docs/10-repo-and-build.md) does much more: role cardinality,
requires-graph validation, contract conformance, zk.lock, UI registry, --check.
This file only proves the load-bearing mechanism.
"""
import json, os, subprocess, sys, tomllib, pathlib

root = pathlib.Path(__file__).resolve().parent

def package_index():
    """Prefer `cargo metadata`; fall back to a raw manifest scan when the build is broken."""
    try:
        md = json.loads(subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--no-deps"],
            cwd=root, stderr=subprocess.DEVNULL))
        out = {}
        for p in md["packages"]:
            zk = (p.get("metadata") or {}).get("zk")
            if zk and "role" in zk:
                out.setdefault(zk["role"], []).append(
                    {"name": p["name"], "dir": pathlib.Path(p["manifest_path"]).parent})
        return out
    except subprocess.CalledProcessError:
        out = {}
        for m in root.glob("packages/*/Cargo.toml"):
            d = tomllib.loads(m.read_text())
            zk = d.get("package", {}).get("metadata", {}).get("zk")
            if zk and "role" in zk:
                out.setdefault(zk["role"], []).append(
                    {"name": d["package"]["name"], "dir": m.parent})
        return out

profile = sys.argv[1]
prof = tomllib.loads((root / "profiles" / f"{profile}.toml").read_text())
out = root / "crates" / "zk-composed"
(out / "src").mkdir(parents=True, exist_ok=True)
index = package_index()

deps, aliases, body = [], [], []
for role in sorted(prof["packages"]):
    want = prof["packages"][role]
    if isinstance(want, dict):                       # external package: { name, path }
        name, pdir = want["name"], (root / want["path"]).resolve()
    else:                                            # in-repo package, resolved by role
        cands = {c["name"]: c for c in index.get(role, [])}
        assert want in cands, f"role {role}: want {want}; candidates {sorted(cands)}"
        name, pdir = want, cands[want]["dir"]
    deps.append(f'{name} = {{ path = "{os.path.relpath(pdir, out)}" }}')
    alias = "pkg_" + role.replace(".", "_")
    aliases.append(f"use {name.replace('-', '_')} as {alias};")
    body.append(f"    items.extend({alias}::package().tools());")

(out / "Cargo.toml").write_text(
    '[package]\nname = "zk-composed"\nversion = "0.0.0"\nedition = "2021"\npublish = false\n\n'
    '[dependencies]\nzk-contract-tool = { path = "../../packages/contract-tool" }\n'
    + "\n".join(deps) + "\n")

(out / "src" / "lib.rs").write_text(
    "// @generated by zk compose -- do not edit\n"
    "#![allow(unused_imports)]\n"
    "use zk_contract_tool::{Tool, ToolPackage};\n"
    + "\n".join(aliases)
    + "\n\npub fn tools() -> Vec<Box<dyn Tool>> {\n    let mut items: Vec<Box<dyn Tool>> = Vec::new();\n"
    + "\n".join(body)
    + "\n    items\n}\n")

label = {k: (v if isinstance(v, str) else v["name"]) for k, v in prof["packages"].items()}
print("composed:", profile, "->", label)
