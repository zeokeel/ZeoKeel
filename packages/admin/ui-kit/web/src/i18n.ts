const dictionaries: Record<AdminLocale, Record<AdminMessageKey, string>> = {
  "zh-CN": zhCN,
  "en-US": enUS,
};

let currentLocale: AdminLocale = "zh-CN";

/** Test/user hook: admin has no language switcher yet; default is zh-CN (e2e contract). */
export function setAdminLocale(locale: AdminLocale): void {
  currentLocale = locale;
}

export function getAdminLocale(): AdminLocale {
  return currentLocale;
}

function format(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match: string, name: string) => {
    const value = vars[name];
    return value === undefined ? match : String(value);
  });
}

export function adminTranslate(
  locale: AdminLocale,
  key: AdminMessageKey,
  vars?: Record<string, string | number>,
): string {
  const template = dictionaries[locale][key];
  return vars === undefined ? template : format(template, vars);
}

/** Module-level translator used by the admin pages (zh-CN by default). */
export function adminT(key: AdminMessageKey, vars?: Record<string, string | number>): string {
  return adminTranslate(currentLocale, key, vars);
}
