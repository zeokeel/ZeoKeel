#[derive(Serialize)]
struct CapabilityJson<'a> {
    id: &'a str,
    path: &'a str,
}

fn scan_capabilities(root: &Path) -> Result<Vec<CapabilityJson<'static>>> {
    let mut out: Vec<CapabilityJson<'static>> = Vec::new();
    let mut roots: BTreeSet<PathBuf> = BTreeSet::new();
    // Every package crate can declare reusable capabilities (`packages/<group>/<pkg>/src`).
    let packages_dir = root.join("packages");
    if packages_dir.is_dir() {
        for group in fs::read_dir(&packages_dir)? {
            let group = group?;
            if !group.file_type()?.is_dir() {
                continue;
            }
            for entry in fs::read_dir(group.path())? {
                let entry = entry?;
                if !entry.file_type()?.is_dir() {
                    continue;
                }
                let src = entry.path().join("src");
                if src.is_dir() {
                    roots.insert(src);
                }
            }
        }
    }
    // Shared implementation libraries are not packages (docs/25 §2).
    let crates_dir = root.join("crates");
    if crates_dir.is_dir() {
        for entry in fs::read_dir(&crates_dir)? {
            let entry = entry?;
            let name = entry.file_name().to_string_lossy().to_string();
            if entry.file_type()?.is_dir() && name.starts_with("zk-kit-") {
                let src = entry.path().join("src");
                if src.is_dir() {
                    roots.insert(src);
                }
            }
        }
    }
    for dir in roots {
        walk_rs(&dir, root, &mut out)?;
    }
    out.sort_by(|a, b| a.id.cmp(b.id).then(a.path.cmp(b.path)));
    Ok(out)
}

/// Minimum capability-registration rule (docs/25 §27): every contract crate and every
/// `crates/zk-kit-*` crate must declare at least one `@capability` in its source.
/// Without this check `zk capability --check` could never detect an *unregistered*
/// public capability (it only compared the comments it found).
fn missing_capability_targets(
    root: &Path,
    manifests: &BTreeMap<String, Manifest>,
    caps: &[CapabilityJson<'static>],
) -> Result<Vec<String>> {
    let mut missing: BTreeSet<String> = BTreeSet::new();
    for manifest in manifests.values() {
        if manifest.kind != "contract" {
            continue;
        }
        let Some(crate_name) = manifest.rust_crate() else {
            continue;
        };
        let dir = find_package_dir(root, &manifest.id)?;
        let src_rel = dir
            .join("src")
            .strip_prefix(root)
            .map(|rel| rel.display().to_string())
            .unwrap_or_else(|_| dir.join("src").display().to_string());
        if !caps.iter().any(|cap| cap.path.starts_with(&src_rel)) {
            missing.insert(format!("package {} (crate {crate_name})", manifest.id));
        }
    }
    let crates_dir = root.join("crates");
    if crates_dir.is_dir() {
        for entry in fs::read_dir(&crates_dir)? {
            let entry = entry?;
            let name = entry.file_name().to_string_lossy().to_string();
            if !entry.file_type()?.is_dir() || !name.starts_with("zk-kit-") {
                continue;
            }
            let src = entry.path().join("src");
            if !src.is_dir() {
                continue;
            }
            let src_rel = src
                .strip_prefix(root)
                .map(|rel| rel.display().to_string())
                .unwrap_or_else(|_| src.display().to_string());
            if !caps.iter().any(|cap| cap.path.starts_with(&src_rel)) {
                missing.insert(format!("crate {name}"));
            }
        }
    }
    Ok(missing.into_iter().collect())
}

fn walk_rs(dir: &Path, root: &Path, out: &mut Vec<CapabilityJson<'static>>) -> Result<()> {
    if !dir.is_dir() {
        return Ok(());
    }
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        let path = entry.path();
        if entry.file_type()?.is_dir() {
            walk_rs(&path, root, out)?;
        } else if path.extension().and_then(|e| e.to_str()) == Some("rs") {
            let text = fs::read_to_string(&path)?;
            for line in text.lines() {
                if let Some(idx) = line.find("@capability ") {
                    let rest = match line.get(idx.saturating_add("@capability ".len())..) {
                        Some(v) => v,
                        None => continue,
                    };
                    let id: String = rest
                        .chars()
                        .take_while(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-'))
                        .collect();
                    if id.is_empty() {
                        continue;
                    }
                    let rel = path
                        .strip_prefix(root)
                        .unwrap_or(&path)
                        .display()
                        .to_string();
                    let id: &'static str = Box::leak(id.into_boxed_str());
                    let rel: &'static str = Box::leak(rel.into_boxed_str());
                    out.push(CapabilityJson { id, path: rel });
                }
            }
        }
    }
    Ok(())
}

fn capability(root: &Path, check: bool) -> Result<()> {
    let manifests = scan_manifests(root)?;
    let caps = scan_capabilities(root)?;
    let missing = missing_capability_targets(root, &manifests, &caps)?;
    if !missing.is_empty() {
        bail!(
            "capability index incomplete: contract/kit crates without a `@capability` declaration: {} \
             (rule: docs/25 §27)",
            missing.join(", ")
        );
    }
    let json = format!("{}\n", serde_json::to_string_pretty(&caps)?);
    let mut md = String::new();
    md.push_str("<!-- @generated by zk capability -- do not edit -->\n\n# Capability Index\n\n");
    md.push_str(&format!(
        "{} capabilities\n\n| id | path |\n| --- | --- |\n",
        caps.len()
    ));
    for cap in &caps {
        md.push_str(&format!("| `{}` | `{}` |\n", cap.id, cap.path));
    }
    let json_path = root.join("shared/contracts/capability-index.json");
    let md_path = root.join("docs/generated/CAPABILITY-INDEX.md");
    if check {
        for (path, expected) in [(&json_path, &json), (&md_path, &md)] {
            let actual = fs::read_to_string(path).unwrap_or_default();
            if actual != *expected {
                bail!("capability index differs: {}", path.display());
            }
        }
        println!("capability: up to date ({} entries)", caps.len());
        return Ok(());
    }
    if let Some(parent) = json_path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(&json_path, json)?;
    fs::write(&md_path, md)?;
    println!("capability: wrote {} entries", caps.len());
    Ok(())
}

fn find(root: &Path, keyword: &str) -> Result<()> {
    let path = root.join("shared/contracts/capability-index.json");
    let text = fs::read_to_string(&path)
        .with_context(|| format!("read {} (run zk capability first)", path.display()))?;
    let value: serde_json::Value = serde_json::from_str(&text)?;
    let mut found = 0usize;
    if let Some(items) = value.as_array() {
        for item in items {
            let id = item.get("id").and_then(|v| v.as_str()).unwrap_or("");
            let p = item.get("path").and_then(|v| v.as_str()).unwrap_or("");
            if id.contains(keyword) || p.contains(keyword) {
                println!("{id}\t{p}");
                found = found.saturating_add(1);
            }
        }
    }
    println!("find: {found} match(es) for {keyword}");
    Ok(())
}

fn lint(root: &Path, duplicates: bool) -> Result<()> {
    let mut bad: Vec<String> = Vec::new();
    for base in ["packages", "apps"] {
        scan_forbidden_dirs(&root.join(base), root, &mut bad)?;
    }
    if !bad.is_empty() {
        bail!("forbidden shared-code locations: {}", bad.join(", "));
    }
    if duplicates {
        println!("lint: duplicate detector is a M0 follow-up task (docs/25 T20); path/import checks passed");
    } else {
        println!("lint: ok (no forbidden utils/helpers/common dirs)");
    }
    Ok(())
}

fn scan_forbidden_dirs(dir: &Path, root: &Path, bad: &mut Vec<String>) -> Result<()> {
    if !dir.is_dir() {
        return Ok(());
    }
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        let path = entry.path();
        if entry.file_type()?.is_dir() {
            let name = entry.file_name().to_string_lossy().to_string();
            let under_kit = path.starts_with(root.join("crates")) && name.starts_with("zk-kit-");
            if matches!(name.as_str(), "utils" | "helpers" | "common" | "misc") && !under_kit {
                bad.push(path.display().to_string());
            } else {
                scan_forbidden_dirs(&path, root, bad)?;
            }
        } else {
            if let Some(name) = path.file_name().and_then(|n| n.to_str()) {
                if matches!(name, "shared.ts" | "lib.ts") {
                    bad.push(path.display().to_string());
                }
            }
        }
    }
    Ok(())
}

