fn admin_registry_ts(resolved: &Resolved) -> Option<String> {
    let mut imports = String::new();
    let mut entries = String::new();
    let mut shell = None;
    let mut index = 0usize;
    for manifest in resolved.manifests.values() {
        if manifest.kind != "ui" {
            continue;
        }
        let Some(ui) = manifest.facets.ui.as_ref() else { continue };
        let Some(role) = manifest.role.as_ref() else { continue };
        if role.name == "admin.shell" {
            imports.push_str(&format!("import {{ components as c{index} }} from \"{}\";\n", ui.package));
            shell = Some(format!("export const AdminShellSlot = c{index}[\"shell.admin\"];\n"));
            index = index.saturating_add(1);
        } else if let Some(key) = role.name.strip_prefix("admin.page.") {
            imports.push_str(&format!("import {{ components as c{index} }} from \"{}\";\n", ui.package));
            entries.push_str(&format!("  {key}: c{index}[\"page.{key}\"],\n"));
            index = index.saturating_add(1);
        }
    }
    if imports.is_empty() {
        return None;
    }
    Some(format!(
        "// @generated by zk compose -- do not edit\n\n{imports}\nexport const ADMIN_PAGES = {{\n{entries}}} as const;\n\n{}\n",
        shell.unwrap_or_default()
    ))
}

fn ui_registry_ts(resolved: &Resolved) -> String {
    let mut imports = String::new();
    let mut spreads = String::new();
    let mut bindings = String::new();
    let mut index = 0usize;
    for pkg in &resolved.packages {
        let Some(manifest) = resolved.manifests.get(&pkg.package_id) else {
            continue;
        };
        if manifest.kind != "ui" {
            continue;
        }
        let Some(ui) = manifest.facets.ui.as_ref() else {
            continue;
        };
        if pkg.role == "ui.kit" || pkg.role.starts_with("admin.") {
            continue;
        }
        imports.push_str(&format!("import {{ components as c{index} }} from \"{}\";\n", ui.package));
        spreads.push_str(&format!("  ...c{index},\n"));
        for contribution in manifest.ui_contributions() {
            if let Some(binding) = slot_binding(&contribution.slot) {
                bindings.push_str(&format!(
                    "export const {binding} = c{index}[\"{}\"];\n",
                    contribution.component
                ));
            }
        }
        index = index.saturating_add(1);
    }
    let settings_provider_stub = if bindings.contains("SettingsProviderSlot") {
        String::new()
    } else {
        "import type { ProviderSettingsProps } from \"@zeokeel/ui-kit\";\nexport function SettingsProviderSlot(_props: ProviderSettingsProps) { return null; }\n".to_owned()
    };
    let skills_stub = if bindings.contains("SkillsSlot") { String::new() } else { "export function SkillsSlot(_props: Record<string, unknown>) { return null; }\n".to_owned() };
    let apps_stub = if bindings.contains("AppsSlot") { String::new() } else { "export function AppsSlot(_props: Record<string, unknown>) { return null; }\n".to_owned() };
    let connectors_stub = if bindings.contains("ConnectorsSlot") { String::new() } else { "export function ConnectorsSlot(_props: Record<string, unknown>) { return null; }\n".to_owned() };
    let login_stub = if bindings.contains("LoginSlot") {
        String::new()
    } else {
        "export function LoginSlot(_props: { serverUrl: string | null; channelLocked: boolean; loading: boolean; error: string | null; onSubmit: (input: { serverUrl?: string; username: string; password: string; deviceName: string }) => void }) { return null; }\n".to_owned()
    };
    format!(
        "// @generated by zk compose -- do not edit\n\n{imports}\nexport const COMPONENTS = {{\n{spreads}}} as const;\n\n{bindings}{login_stub}{settings_provider_stub}{skills_stub}{connectors_stub}{apps_stub}"
    )
}

fn ui_contributions_json(resolved: &Resolved) -> Result<String> {
    let mut out: Vec<serde_json::Value> = Vec::new();
    for pkg in &resolved.packages {
        let Some(manifest) = resolved.manifests.get(&pkg.package_id) else {
            continue;
        };
        if manifest.kind != "ui" {
            continue;
        }
        for contribution in manifest.ui_contributions() {
            out.push(serde_json::json!({
                "package": manifest.id,
                "role": pkg.role,
                "slot": contribution.slot,
                "component": contribution.component,
                "order": contribution.order,
            }));
        }
    }
    out.sort_by_key(|v| v.get("slot").and_then(|s| s.as_str()).unwrap_or("").to_owned());
    Ok(format!("{}\n", serde_json::to_string_pretty(&out)?))
}

fn generated_packages_rs(resolved: &Resolved) -> String {
    let mut out = String::new();
    out.push_str("// @generated by zk compose -- do not edit\n#![allow(dead_code)]\n\n");
    out.push_str(&format!(
        "pub const EDITION: &str = \"{}\";\n",
        resolved.edition
    ));
    out.push_str("pub const PACKAGES: &[&str] = &[");
    for pkg in &resolved.packages {
        out.push_str(&format!("\"{}\",", pkg.package_id));
    }
    out.push_str("];\n");
    out
}

#[derive(Serialize)]
struct PackageJson<'a> {
    id: &'a str,
    version: &'a str,
    kind: &'a str,
    roles: Vec<&'a str>,
}

#[derive(Serialize)]
struct RoleJson<'a> {
    package: &'a str,
    crate_name: &'a str,
    contract: &'a str,
    cardinality: &'a str,
}

fn packages_json(resolved: &Resolved) -> Result<String> {
    let mut out: Vec<PackageJson> = Vec::new();
    let mut seen = BTreeSet::new();
    for pkg in &resolved.packages {
        if !seen.insert(pkg.package_id.clone()) {
            continue;
        }
        if let Some(manifest) = resolved.manifests.get(&pkg.package_id) {
            out.push(PackageJson {
                id: &manifest.id,
                version: &manifest.version,
                kind: &manifest.kind,
                roles: manifest
                    .role_decls()
                    .iter()
                    .map(|r| r.name.as_str())
                    .collect(),
            });
        }
    }
    Ok(format!("{}\n", serde_json::to_string_pretty(&out)?))
}

fn roles_json(resolved: &Resolved) -> Result<String> {
    let mut map: BTreeMap<String, RoleJson> = BTreeMap::new();
    for pkg in &resolved.packages {
        map.insert(
            pkg.role.clone(),
            RoleJson {
                package: &pkg.package_id,
                crate_name: &pkg.crate_name,
                contract: &pkg.contract,
                cardinality: &pkg.cardinality,
            },
        );
    }
    Ok(format!("{}\n", serde_json::to_string_pretty(&map)?))
}

fn package_index_md(resolved: &Resolved) -> String {
    let mut out = String::new();
    out.push_str("<!-- @generated by zk compose -- do not edit -->\n\n# Package Index\n\n");
    out.push_str(&format!(
        "edition `{}` · channel `{}` · {} packages\n\n",
        resolved.edition,
        resolved.channel,
        resolved.packages.len()
    ));
    out.push_str(
        "| role | package | crate | contract | cardinality |\n| --- | --- | --- | --- | --- |\n",
    );
    for pkg in &resolved.packages {
        out.push_str(&format!(
            "| `{}` | `{}` | `{}` | `{}` | {} |\n",
            pkg.role, pkg.package_id, pkg.crate_name, pkg.contract, pkg.cardinality
        ));
    }
    out
}

#[derive(Serialize)]
struct CapabilityJson<'a> {
    id: &'a str,
    path: &'a str,
}

fn scan_capabilities(root: &Path) -> Result<Vec<CapabilityJson<'static>>> {
    let mut out: Vec<CapabilityJson<'static>> = Vec::new();
    let mut roots: Vec<PathBuf> = Vec::new();
    let contracts = root.join("packages/contracts");
    if contracts.is_dir() {
        for entry in fs::read_dir(&contracts)? {
            let entry = entry?;
            if entry.file_type()?.is_dir() {
                roots.push(entry.path().join("src"));
            }
        }
    }
    let crates_dir = root.join("crates");
    if crates_dir.is_dir() {
        for entry in fs::read_dir(&crates_dir)? {
            let entry = entry?;
            let name = entry.file_name().to_string_lossy().to_string();
            if entry.file_type()?.is_dir() && name.starts_with("zk-kit-") {
                roots.push(entry.path().join("src"));
            }
        }
    }
    for dir in roots {
        walk_rs(&dir, root, &mut out)?;
    }
    out.sort_by(|a, b| a.id.cmp(b.id).then(a.path.cmp(b.path)));
    Ok(out)
}

fn walk_rs(dir: &Path, root: &Path, out: &mut Vec<CapabilityJson<'static>>) -> Result<()> {
    if !dir.is_dir() {
        return Ok(());
    }
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        let path = entry.path();
        if entry.file_type()?.is_dir() {
            walk_rs(&path, root, out)?;
        } else if path.extension().and_then(|e| e.to_str()) == Some("rs") {
            let text = fs::read_to_string(&path)?;
            for line in text.lines() {
                if let Some(idx) = line.find("@capability ") {
                    let rest = match line.get(idx.saturating_add("@capability ".len())..) {
                        Some(v) => v,
                        None => continue,
                    };
                    let id: String = rest
                        .chars()
                        .take_while(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-'))
                        .collect();
                    if id.is_empty() {
                        continue;
                    }
                    let rel = path
                        .strip_prefix(root)
                        .unwrap_or(&path)
                        .display()
                        .to_string();
                    let id: &'static str = Box::leak(id.into_boxed_str());
                    let rel: &'static str = Box::leak(rel.into_boxed_str());
                    out.push(CapabilityJson { id, path: rel });
                }
            }
        }
    }
    Ok(())
}

fn capability(root: &Path, check: bool) -> Result<()> {
    let caps = scan_capabilities(root)?;
    let json = format!("{}\n", serde_json::to_string_pretty(&caps)?);
    let mut md = String::new();
    md.push_str("<!-- @generated by zk capability -- do not edit -->\n\n# Capability Index\n\n");
    md.push_str(&format!(
        "{} capabilities\n\n| id | path |\n| --- | --- |\n",
        caps.len()
    ));
    for cap in &caps {
        md.push_str(&format!("| `{}` | `{}` |\n", cap.id, cap.path));
    }
    let json_path = root.join("shared/contracts/capability-index.json");
    let md_path = root.join("docs/generated/CAPABILITY-INDEX.md");
    if check {
        for (path, expected) in [(&json_path, &json), (&md_path, &md)] {
            let actual = fs::read_to_string(path).unwrap_or_default();
            if actual != *expected {
                bail!("capability index differs: {}", path.display());
            }
        }
        println!("capability: up to date ({} entries)", caps.len());
        return Ok(());
    }
    if let Some(parent) = json_path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(&json_path, json)?;
    fs::write(&md_path, md)?;
    println!("capability: wrote {} entries", caps.len());
    Ok(())
}

fn find(root: &Path, keyword: &str) -> Result<()> {
    let path = root.join("shared/contracts/capability-index.json");
    let text = fs::read_to_string(&path)
        .with_context(|| format!("read {} (run zk capability first)", path.display()))?;
    let value: serde_json::Value = serde_json::from_str(&text)?;
    let mut found = 0usize;
    if let Some(items) = value.as_array() {
        for item in items {
            let id = item.get("id").and_then(|v| v.as_str()).unwrap_or("");
            let p = item.get("path").and_then(|v| v.as_str()).unwrap_or("");
            if id.contains(keyword) || p.contains(keyword) {
                println!("{id}\t{p}");
                found = found.saturating_add(1);
            }
        }
    }
    println!("find: {found} match(es) for {keyword}");
    Ok(())
}

fn lint(root: &Path, duplicates: bool) -> Result<()> {
    let mut bad: Vec<String> = Vec::new();
    for base in ["packages", "apps"] {
        scan_forbidden_dirs(&root.join(base), root, &mut bad)?;
    }
    if !bad.is_empty() {
        bail!("forbidden shared-code locations: {}", bad.join(", "));
    }
    if duplicates {
        println!("lint: duplicate detector is a M0 follow-up task (docs/25 T20); path/import checks passed");
    } else {
        println!("lint: ok (no forbidden utils/helpers/common dirs)");
    }
    Ok(())
}

fn scan_forbidden_dirs(dir: &Path, root: &Path, bad: &mut Vec<String>) -> Result<()> {
    if !dir.is_dir() {
        return Ok(());
    }
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        let path = entry.path();
        if entry.file_type()?.is_dir() {
            let name = entry.file_name().to_string_lossy().to_string();
            let under_kit = path.starts_with(root.join("crates")) && name.starts_with("zk-kit-");
            if matches!(name.as_str(), "utils" | "helpers" | "common" | "misc") && !under_kit {
                bad.push(path.display().to_string());
            } else {
                scan_forbidden_dirs(&path, root, bad)?;
            }
        } else {
            if let Some(name) = path.file_name().and_then(|n| n.to_str()) {
                if matches!(name, "shared.ts" | "lib.ts") {
                    bad.push(path.display().to_string());
                }
            }
        }
    }
    Ok(())
}
