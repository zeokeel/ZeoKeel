fn admin_registry_ts(resolved: &Resolved) -> String {
    let mut imports = String::new();
    let mut entries = String::new();
    let mut shell = None;
    let mut index = 0usize;
    for pkg in &resolved.packages {
        // Only packages selected by the resolved composition may contribute admin
        // pages; scanning all manifests leaks enterprise pages into the personal baseline.
        let Some(manifest) = resolved.manifests.get(&pkg.package_id) else {
            continue;
        };
        if manifest.kind != "ui" {
            continue;
        }
        let Some(ui) = manifest.facets.ui.as_ref() else {
            continue;
        };
        if pkg.role == "admin.shell" {
            imports.push_str(&format!(
                "import {{ components as c{index} }} from \"{}\";\n",
                ui.package
            ));
            shell = Some(format!(
                "export const AdminShellSlot = c{index}[\"shell.admin\"];\n"
            ));
            index = index.saturating_add(1);
        } else if let Some(key) = pkg.role.strip_prefix("admin.page.") {
            imports.push_str(&format!(
                "import {{ components as c{index} }} from \"{}\";\n",
                ui.package
            ));
            entries.push_str(&format!("  {key}: c{index}[\"page.{key}\"],\n"));
            index = index.saturating_add(1);
        }
    }
    if imports.is_empty() {
        // Editions without admin pages (personal) still need a deterministic, buildable
        // generated module: the admin SPA must typecheck in the committed baseline.
        return "// @generated by zk compose -- do not edit\n\n\
import type { ReactNode } from \"react\";\n\
import type { AdminPage } from \"@zeokeel/admin-shell\";\n\n\
 type NoopPage = (props: { onError: (message: string) => void }) => null;\n\n\
export const ADMIN_PAGES: Partial<Record<AdminPage, NoopPage>> = {};\n\n\
export function AdminShellSlot(_props: { renderPage: (page: AdminPage) => ReactNode }): null {\n  return null;\n}\n"
            .to_owned();
    }
    format!(
        "// @generated by zk compose -- do not edit\n\n{imports}\nexport const ADMIN_PAGES = {{\n{entries}}} as const;\n\n{}\n",
        shell.unwrap_or_default()
    )
}

fn ui_registry_ts(resolved: &Resolved) -> String {
    let mut imports = String::new();
    let mut spreads = String::new();
    let mut bindings = String::new();
    let mut index = 0usize;
    for pkg in &resolved.packages {
        let Some(manifest) = resolved.manifests.get(&pkg.package_id) else {
            continue;
        };
        if manifest.kind != "ui" {
            continue;
        }
        let Some(ui) = manifest.facets.ui.as_ref() else {
            continue;
        };
        if pkg.role == "ui.kit" || pkg.role.starts_with("admin.") {
            continue;
        }
        imports.push_str(&format!(
            "import {{ components as c{index} }} from \"{}\";\n",
            ui.package
        ));
        spreads.push_str(&format!("  ...c{index},\n"));
        for contribution in manifest.ui_contributions() {
            if let Some(binding) = slot_binding(&contribution.slot) {
                bindings.push_str(&format!(
                    "export const {binding} = c{index}[\"{}\"];\n",
                    contribution.component
                ));
            }
        }
        index = index.saturating_add(1);
    }
    let settings_provider_stub = if bindings.contains("SettingsProviderSlot") {
        String::new()
    } else {
        "import type { ProviderSettingsProps } from \"@zeokeel/ui-kit\";\nexport function SettingsProviderSlot(_props: ProviderSettingsProps) { return null; }\n".to_owned()
    };
    let skills_stub = if bindings.contains("SkillsSlot") {
        String::new()
    } else {
        "export function SkillsSlot(_props: Record<string, unknown>) { return null; }\n".to_owned()
    };
    let apps_stub = if bindings.contains("AppsSlot") {
        String::new()
    } else {
        "export function AppsSlot(_props: Record<string, unknown>) { return null; }\n".to_owned()
    };
    let app_surface_stub = if bindings.contains("AppSurfaceSlot") {
        String::new()
    } else {
        "export function AppSurfaceSlot(_props: Record<string, unknown>) { return null; }\n"
            .to_owned()
    };
    let connectors_stub = if bindings.contains("ConnectorsSlot") {
        String::new()
    } else {
        "export function ConnectorsSlot(_props: Record<string, unknown>) { return null; }\n"
            .to_owned()
    };
    let login_stub = if bindings.contains("LoginSlot") {
        String::new()
    } else {
        "export function LoginSlot(_props: { serverUrl: string | null; channelLocked: boolean; loading: boolean; error: string | null; onSubmit: (input: { serverUrl?: string; username: string; password: string; deviceName: string }) => void }) { return null; }\n".to_owned()
    };
    format!(
        "// @generated by zk compose -- do not edit\n\n{imports}\nexport const COMPONENTS = {{\n{spreads}}} as const;\n\n{bindings}{login_stub}{settings_provider_stub}{skills_stub}{connectors_stub}{apps_stub}{app_surface_stub}"
    )
}

fn ui_contributions_json(resolved: &Resolved) -> Result<String> {
    let mut out: Vec<serde_json::Value> = Vec::new();
    for pkg in &resolved.packages {
        let Some(manifest) = resolved.manifests.get(&pkg.package_id) else {
            continue;
        };
        if manifest.kind != "ui" {
            continue;
        }
        for contribution in manifest.ui_contributions() {
            out.push(serde_json::json!({
                "package": manifest.id,
                "role": pkg.role,
                "slot": contribution.slot,
                "component": contribution.component,
                "order": contribution.order,
            }));
        }
    }
    out.sort_by_key(|v| {
        v.get("slot")
            .and_then(|s| s.as_str())
            .unwrap_or("")
            .to_owned()
    });
    Ok(format!("{}\n", stable_json(&out)?))
}

