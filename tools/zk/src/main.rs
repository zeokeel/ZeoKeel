        assert_eq!(first.chars().nth(14), Some('5'));
        assert_eq!(first.chars().nth(19), Some('8'));
        assert_eq!(first, sbom_uuid(&[0_u8; 32]));
        assert_ne!(first, sbom_uuid(&[1_u8; 32]));
