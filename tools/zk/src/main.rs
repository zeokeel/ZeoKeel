#![forbid(unsafe_code)]
//! ZeoKeel `zk` composition CLI (minimal M0 subset).
//!
//! Commands: `validate`, `compose [--check]`, `plan`, `docs [--check]`,
//! `capability [--check]`, `find <kw>`, `lint [--duplicates]`, `channel`,
//! `db lock [--check]`.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{bail, Context, Result};
use serde::{Deserialize, Serialize};

#[allow(dead_code)]
const GENERATED: &str = "@generated by zk compose -- do not edit";

fn main() {
    if let Err(err) = run() {
        eprintln!("zk: {err:#}");
        std::process::exit(1);
    }
}

fn run() -> Result<()> {
    let mut args = std::env::args().skip(1);
    let command = args
        .next()
        .context("usage: zk <validate|compose|plan|docs|capability|find|lint|channel|db>")?;
    let root = find_root()?;
    let rest: Vec<String> = args.collect();
    match command.as_str() {
        "validate" => validate(&root),
        "compose" => {
            let flags = Flags::parse(&rest, true)?
                .context("compose requires --edition (and --channel, docs/24 §1.2)")?;
            let check = rest.iter().any(|a| a == "--check");
            compose(&root, &flags, check)
        }
        "plan" => {
            let flags = Flags::parse(&rest, true)?
                .context("plan requires --edition (and --channel, docs/24 §1.2)")?;
            plan(&root, &flags)
        }
        "docs" => {
            let check = rest.iter().any(|a| a == "--check");
            docs(&root, check)
        }
        "capability" => {
            let check = rest.iter().any(|a| a == "--check");
            capability(&root, check)
        }
        "find" => {
            let keyword = rest.first().context("usage: zk find <keyword>")?.clone();
            find(&root, &keyword)
        }
        "lint" => lint(&root, rest.iter().any(|a| a == "--duplicates")),
        "channel" => channel_command(&root, &rest),
        "db" => {
            let sub = rest.first().map(String::as_str).unwrap_or("");
            if sub.is_empty() {
                bail!("usage: zk db lock [--check]");
            }
            if sub != "lock" {
                bail!("unknown db subcommand: {sub}");
            }
            db_lock(&root, rest.iter().any(|a| a == "--check"))
        }
        other => bail!("unknown command: {other}"),
    }
}

fn find_root() -> Result<PathBuf> {
    let mut dir = std::env::current_dir().context("current_dir")?;
    loop {
        if dir.join("zk.toml").is_file() {
            return Ok(dir);
        }
        if !dir.pop() {
            bail!("zk.toml not found (run from the repo)");
        }
    }
}

#[derive(Debug, Clone)]
struct Flags {
    edition: String,
    profile: String,
    channel: String,
}

impl Flags {
    /// Parse `--edition/--profile/--channel`. `--profile` defaults to `default`;
    /// `--channel` must be explicit for compose/plan (docs/24 §1.2: no default).
    fn parse(args: &[String], require_channel: bool) -> Result<Option<Self>> {
        let mut map: BTreeMap<&str, String> = BTreeMap::new();
        let mut i = 0;
        while let Some(arg) = args.get(i) {
            let key = match arg.as_str() {
                "--edition" => "--edition",
                "--profile" => "--profile",
                "--channel" => "--channel",
                _ => {
                    i = i.saturating_add(1);
                    continue;
                }
            };
            let value = args
                .get(i.saturating_add(1))
                .with_context(|| format!("{key} needs a value"))?;
            map.insert(key, value.clone());
            i = i.saturating_add(2);
        }
        let edition = match map.get("--edition") {
            Some(v) => v.clone(),
            None => return Ok(None),
        };
        let profile = map
            .get("--profile")
            .cloned()
            .unwrap_or_else(|| "default".to_owned());
        let channel = match map.get("--channel").cloned() {
            Some(value) => value,
            None if require_channel => bail!(
                "--channel is required (docs/24 §1.2: no default); \
                 pass --channel official|beta|oem-<customer>"
            ),
            None => "official".to_owned(),
        };
        Ok(Some(Self {
            edition,
            profile,
            channel,
        }))
    }
}

