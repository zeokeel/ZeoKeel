#![forbid(unsafe_code)]
//! ZeoKeel `zk` composition CLI (minimal M0 subset).
//!
//! Commands: `validate`, `compose [--check]`, `plan`, `docs [--check]`,
//! `capability [--check]`, `find <kw>`, `lint [--duplicates]`, `channel`,
//! `db lock [--check]`, `sbom [--check]`.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{bail, Context, Result};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

#[allow(dead_code)]
const GENERATED: &str = "@generated by zk compose -- do not edit";

fn main() {
    if let Err(err) = run() {
        eprintln!("zk: {err:#}");
        std::process::exit(1);
    }
}

fn run() -> Result<()> {
    let mut args = std::env::args().skip(1);
    let command = args
        .next()
        .context("usage: zk <validate|compose|plan|docs|capability|find|lint|channel|db|sbom>")?;
    let root = find_root()?;
    let rest: Vec<String> = args.collect();
    match command.as_str() {
        "validate" => validate(&root),
        "sbom" => {
            let sbom_args = SbomArgs::parse(&rest)?;
            sbom(&root, &sbom_args)
        }
        "compose" => {
            let flags = Flags::parse(&rest, true)?
                .context("compose requires --edition (and --channel, docs/24 §1.2)")?;
            let check = rest.iter().any(|a| a == "--check");
            compose(&root, &flags, check)
        }
        "plan" => {
            let flags = Flags::parse(&rest, true)?
                .context("plan requires --edition (and --channel, docs/24 §1.2)")?;
            plan(&root, &flags)
        }
        "docs" => {
            let check = rest.iter().any(|a| a == "--check");
            docs(&root, check)
        }
        "capability" => {
            let check = rest.iter().any(|a| a == "--check");
            capability(&root, check)
        }
        "find" => {
            let keyword = rest.first().context("usage: zk find <keyword>")?.clone();
            find(&root, &keyword)
        }
        "lint" => lint(
            &root,
            rest.iter().any(|a| a == "--duplicates"),
            rest.iter().any(|a| a == "--write-baseline"),
        ),
        "channel" => channel_command(&root, &rest),
        "db" => {
            let sub = rest.first().map(String::as_str).unwrap_or("");
            if sub.is_empty() {
                bail!("usage: zk db lock [--check]");
            }
            if sub != "lock" {
                bail!("unknown db subcommand: {sub}");
            }
            db_lock(&root, rest.iter().any(|a| a == "--check"))
        }
        other => bail!("unknown command: {other}"),
    }
}

#[derive(Debug, Clone)]
struct SbomArgs {
    flags: Flags,
    output: Option<PathBuf>,
    check: bool,
}

impl SbomArgs {
    /// Parse `sbom` arguments: edition/profile/channel are required like compose;
    /// `--output` is optional (defaults to `target/evidence/sbom/zeokeel-<edition>.cdx.json`).
    fn parse(args: &[String]) -> Result<Self> {
        let mut edition: Option<String> = None;
        let mut profile: Option<String> = None;
        let mut channel: Option<String> = None;
        let mut output: Option<String> = None;
        let mut check = false;
        let mut index = 0;
        while let Some(argument) = args.get(index) {
            match argument.as_str() {
                "--check" => {
                    check = true;
                    index = index.saturating_add(1);
                }
                "--edition" | "--profile" | "--channel" | "--output" => {
                    let value = args
                        .get(index.saturating_add(1))
                        .with_context(|| format!("{argument} needs a value"))?
                        .clone();
                    match argument.as_str() {
                        "--edition" => edition = Some(value),
                        "--profile" => profile = Some(value),
                        "--channel" => channel = Some(value),
                        "--output" => output = Some(value),
                        _ => bail!("unknown sbom argument: {argument}"),
                    }
                    index = index.saturating_add(2);
                }
                other => bail!("unknown sbom argument: {other}"),
            }
        }
        let edition = edition.context("sbom requires --edition <personal|enterprise>")?;
        let channel =
            channel.context("sbom requires --channel <channel> (docs/24 §1.2: no default)")?;
        Ok(Self {
            flags: Flags {
                edition,
                profile: profile.unwrap_or_else(|| "default".to_owned()),
                channel,
            },
            output: output.map(PathBuf::from),
            check,
        })
    }
}

/// One CycloneDX component; serialized through [`stable_json`] for byte stability.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
struct SbomComponent {
    #[serde(rename = "type")]
    component_type: String,
    name: String,
    version: String,
    purl: String,
    #[serde(rename = "bom-ref")]
    bom_ref: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    licenses: Option<Vec<serde_json::Value>>,
    #[serde(skip_serializing_if = "Option::is_none")]
    hashes: Option<Vec<serde_json::Value>>,
}

fn sbom_component(
    name: &str,
    version: &str,
    purl: String,
    license: Option<&str>,
    checksum: Option<&str>,
) -> SbomComponent {
    let licenses = license.map(|value| vec![serde_json::json!({ "expression": value })]);
    let hashes = checksum
        .filter(|value| !value.is_empty())
        .map(|value| vec![serde_json::json!({ "alg": "SHA-256", "content": value })]);
    SbomComponent {
        component_type: "library".to_owned(),
        name: name.to_owned(),
        version: version.to_owned(),
        bom_ref: purl.clone(),
        purl,
        licenses,
        hashes,
    }
}

/// Generate a CycloneDX 1.5 SBOM for the workspace (offline, deterministic).
fn sbom(root: &Path, args: &SbomArgs) -> Result<()> {
    // Reuse the same edition/profile/channel validation as compose/plan.
    resolve(root, &args.flags)?;
    let (root_name, root_version) = workspace_identity(root)?;
    let components = collect_sbom_components(root)?;
    let component_count = components.len();
    let rendered = render_sbom(&root_name, &root_version, components)?;
    let path = sbom_output_path(root, args);
    if args.check {
        verify_sbom(&path, &rendered)?;
        println!("sbom: up to date ({})", path.display());
        return Ok(());
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)
            .with_context(|| format!("create SBOM directory {}", parent.display()))?;
    }
    fs::write(&path, rendered).with_context(|| format!("write SBOM {}", path.display()))?;
    println!(
        "sbom: wrote {} ({} components, CycloneDX 1.5)",
        path.display(),
        component_count
    );
    Ok(())
}

fn sbom_output_path(root: &Path, args: &SbomArgs) -> PathBuf {
    match &args.output {
        Some(path) if path.is_absolute() => path.clone(),
        Some(path) => root.join(path),
        None => root.join(format!(
            "target/evidence/sbom/zeokeel-{}.cdx.json",
            args.flags.edition
        )),
    }
}

fn verify_sbom(path: &Path, rendered: &str) -> Result<()> {
    let actual = fs::read_to_string(path).with_context(|| {
        format!(
            "SBOM not found: {}; run `zk sbom --output {}`",
            path.display(),
            path.display()
        )
    })?;
    if actual != rendered {
        bail!(
            "SBOM out of date: {}; run `zk sbom --output {}`",
            path.display(),
            path.display()
        );
    }
    Ok(())
}

fn workspace_identity(root: &Path) -> Result<(String, String)> {
    let package = fs::read_to_string(root.join("package.json"))
        .ok()
        .and_then(|text| serde_json::from_str::<serde_json::Value>(&text).ok());
    let name = package
        .as_ref()
        .and_then(|value| value.get("name"))
        .and_then(serde_json::Value::as_str)
        .filter(|value| !value.is_empty())
        .unwrap_or("ZeoKeel")
        .to_owned();
    let version = package
        .as_ref()
        .and_then(|value| value.get("version"))
        .and_then(serde_json::Value::as_str)
        .filter(|value| !value.is_empty())
        .unwrap_or(env!("CARGO_PKG_VERSION"))
        .to_owned();
    Ok((name, version))
}

fn collect_sbom_components(root: &Path) -> Result<Vec<SbomComponent>> {
    let licenses = workspace_licenses(root)?;
    let mut by_purl: BTreeMap<String, SbomComponent> = BTreeMap::new();
    for component in cargo_components(root, &licenses)? {
        by_purl.insert(component.purl.clone(), component);
    }
    for component in pnpm_components(root)? {
        by_purl.entry(component.purl.clone()).or_insert(component);
    }
    Ok(by_purl.into_values().collect())
}

/// Licenses for workspace packages from `cargo metadata --no-deps --offline`.
///
/// Dependency licenses are intentionally not guessed: Cargo.lock only has
/// name/version/checksum, and full license resolution is a later SBOM extension.
fn workspace_licenses(root: &Path) -> Result<BTreeMap<(String, String), String>> {
    let output = std::process::Command::new("cargo")
        .args([
            "metadata",
            "--format-version",
            "1",
            "--no-deps",
            "--offline",
        ])
        .current_dir(root)
        .output()
        .context("run cargo metadata --no-deps --offline")?;
    if !output.status.success() {
        bail!(
            "cargo metadata --no-deps --offline failed: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        );
    }
    let value: serde_json::Value =
        serde_json::from_slice(&output.stdout).context("parse cargo metadata JSON")?;
    let packages = value
        .get("packages")
        .and_then(serde_json::Value::as_array)
        .context("cargo metadata has no packages[]")?;
    let mut licenses = BTreeMap::new();
    for package in packages {
        let Some(name) = package.get("name").and_then(serde_json::Value::as_str) else {
            continue;
        };
        let Some(version) = package.get("version").and_then(serde_json::Value::as_str) else {
            continue;
        };
        if let Some(license) = package
            .get("license")
            .and_then(serde_json::Value::as_str)
            .filter(|value| !value.trim().is_empty())
        {
            licenses.insert((name.to_owned(), version.to_owned()), license.to_owned());
        }
    }
    Ok(licenses)
}

fn cargo_components(
    root: &Path,
    licenses: &BTreeMap<(String, String), String>,
) -> Result<Vec<SbomComponent>> {
    let path = root.join("Cargo.lock");
    let text = fs::read_to_string(&path).with_context(|| format!("read {}", path.display()))?;
    let value: toml::Value = toml::from_str(&text).context("parse Cargo.lock")?;
    let packages = value
        .get("package")
        .and_then(toml::Value::as_array)
        .context("Cargo.lock has no [[package]] entries")?;
    let mut components = Vec::new();
    for package in packages {
        let name = package
            .get("name")
            .and_then(toml::Value::as_str)
            .context("Cargo.lock package missing name")?;
        let version = package
            .get("version")
            .and_then(toml::Value::as_str)
            .context("Cargo.lock package missing version")?;
        let checksum = package.get("checksum").and_then(toml::Value::as_str);
        let license = licenses
            .get(&(name.to_owned(), version.to_owned()))
            .map(String::as_str);
        components.push(sbom_component(
            name,
            version,
            format!("pkg:cargo/{name}@{version}"),
            license,
            checksum,
        ));
    }
    Ok(components)
}

fn pnpm_workspace_patterns(root: &Path) -> Result<Vec<String>> {
    let path = root.join("pnpm-workspace.yaml");
    let Ok(text) = fs::read_to_string(&path) else {
        return Ok(Vec::new());
    };
    Ok(parse_workspace_patterns(&text))
}

fn parse_workspace_patterns(text: &str) -> Vec<String> {
    let mut in_packages = false;
    let mut patterns = Vec::new();
    for line in text.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        if !in_packages {
            if trimmed == "packages:" {
                in_packages = true;
            }
            continue;
        }
        if !(line.starts_with(' ') || line.starts_with('\t')) && !trimmed.starts_with('-') {
            break;
        }
        if let Some(rest) = trimmed.strip_prefix('-') {
            let pattern = rest.trim().trim_matches('"').trim_matches('\'');
            if !pattern.is_empty() {
                patterns.push(pattern.to_owned());
            }
        }
    }
    patterns
}

fn expand_workspace_pattern(root: &Path, pattern: &str) -> Result<Vec<PathBuf>> {
    let segments: Vec<&str> = pattern.split('/').filter(|part| !part.is_empty()).collect();
    expand_pattern_segments(root, &segments)
}

fn expand_pattern_segments(base: &Path, segments: &[&str]) -> Result<Vec<PathBuf>> {
    let Some((segment, rest)) = segments.split_first() else {
        return Ok(vec![base.to_path_buf()]);
    };
    if *segment == "*" {
        let Ok(entries) = fs::read_dir(base) else {
            return Ok(Vec::new());
        };
        let mut directories: Vec<PathBuf> = entries
            .filter_map(Result::ok)
            .map(|entry| entry.path())
            .filter(|path| path.is_dir())
            .collect();
        directories.sort();
        let mut found = Vec::new();
        for directory in directories {
            let Some(name) = directory.file_name().and_then(|value| value.to_str()) else {
                continue;
            };
            if name.starts_with('.') || name == "node_modules" || name == "target" {
                continue;
            }
            found.extend(expand_pattern_segments(&directory, rest)?);
        }
        return Ok(found);
    }
    let next = base.join(segment);
    if next.is_dir() {
        expand_pattern_segments(&next, rest)
    } else {
        Ok(Vec::new())
    }
}

fn pnpm_components(root: &Path) -> Result<Vec<SbomComponent>> {
    let patterns = pnpm_workspace_patterns(root)?;
    let mut directories = BTreeSet::new();
    for pattern in patterns {
        for directory in expand_workspace_pattern(root, &pattern)? {
            directories.insert(directory);
        }
    }
    let mut components = Vec::new();
    for directory in directories {
        if let Some(component) = pnpm_component(&directory)? {
            components.push(component);
        }
    }
    Ok(components)
}

fn pnpm_component(directory: &Path) -> Result<Option<SbomComponent>> {
    let path = directory.join("package.json");
    if !path.is_file() {
        return Ok(None);
    }
    let text = fs::read_to_string(&path).with_context(|| format!("read {}", path.display()))?;
    let value: serde_json::Value =
        serde_json::from_str(&text).with_context(|| format!("parse {}", path.display()))?;
    let Some(name) = value.get("name").and_then(serde_json::Value::as_str) else {
        bail!("{} has no package name", path.display());
    };
    let Some(version) = value.get("version").and_then(serde_json::Value::as_str) else {
        bail!("{} has no package version", path.display());
    };
    let license = value.get("license").and_then(serde_json::Value::as_str);
    let purl = npm_purl(name, version);
    Ok(Some(sbom_component(name, version, purl, license, None)))
}

fn npm_purl(name: &str, version: &str) -> String {
    match name.strip_prefix('@') {
        Some(scoped) => format!("pkg:npm/%40{scoped}@{version}"),
        None => format!("pkg:npm/{name}@{version}"),
    }
}

fn render_sbom(
    root_name: &str,
    root_version: &str,
    mut components: Vec<SbomComponent>,
) -> Result<String> {
    components.sort_by(|left, right| {
        left.purl
            .cmp(&right.purl)
            .then_with(|| left.name.cmp(&right.name))
            .then_with(|| left.version.cmp(&right.version))
    });
    components.dedup_by(|left, right| left.purl == right.purl);
    let content = serde_json::json!({
        "bomFormat": "CycloneDX",
        "specVersion": "1.5",
        "version": 1,
        "metadata": {
            "component": {
                "type": "application",
                "name": root_name,
                "version": root_version,
                "bom-ref": "workspace-root",
            }
        },
        "components": components,
    });
    let canonical = stable_json(&content)?;
    let digest = Sha256::digest(canonical.as_bytes());
    let serial = sbom_uuid(digest.as_slice());
    let mut document = content;
    let Some(object) = document.as_object_mut() else {
        bail!("SBOM document is not an object");
    };
    object.insert(
        "serialNumber".to_owned(),
        serde_json::json!(format!("urn:uuid:{serial}")),
    );
    stable_json(&document)
}

/// Deterministic URN UUID derived from the SHA-256 of the SBOM content.
fn sbom_uuid(digest: &[u8]) -> String {
    let hex: String = digest
        .iter()
        .take(16)
        .map(|byte| format!("{byte:02x}"))
        .collect();
    let mut characters: Vec<char> = hex.chars().collect();
    if let Some(character) = characters.get_mut(12) {
        *character = '5';
    }
    if let Some(character) = characters.get_mut(16) {
        *character = '8';
    }
    let mut grouped = String::new();
    for (index, character) in characters.iter().enumerate() {
        if matches!(index, 8 | 12 | 16 | 20) {
            grouped.push('-');
        }
        grouped.push(*character);
    }
    grouped
}

fn find_root() -> Result<PathBuf> {
    let mut dir = std::env::current_dir().context("current_dir")?;
    loop {
        if dir.join("zk.toml").is_file() {
            return Ok(dir);
        }
        if !dir.pop() {
            bail!("zk.toml not found (run from the repo)");
        }
    }
}

#[derive(Debug, Clone)]
struct Flags {
    edition: String,
    profile: String,
    channel: String,
}

impl Flags {
    /// Parse `--edition/--profile/--channel`. `--profile` defaults to `default`;
    /// `--channel` must be explicit for compose/plan (docs/24 §1.2: no default).
    fn parse(args: &[String], require_channel: bool) -> Result<Option<Self>> {
        let mut map: BTreeMap<&str, String> = BTreeMap::new();
        let mut i = 0;
        while let Some(arg) = args.get(i) {
            let key = match arg.as_str() {
                "--edition" => "--edition",
                "--profile" => "--profile",
                "--channel" => "--channel",
                _ => {
                    i = i.saturating_add(1);
                    continue;
                }
            };
            let value = args
                .get(i.saturating_add(1))
                .with_context(|| format!("{key} needs a value"))?;
            map.insert(key, value.clone());
            i = i.saturating_add(2);
        }
        let edition = match map.get("--edition") {
            Some(v) => v.clone(),
            None => return Ok(None),
        };
        let profile = map
            .get("--profile")
            .cloned()
            .unwrap_or_else(|| "default".to_owned());
        let channel = match map.get("--channel").cloned() {
            Some(value) => value,
            None if require_channel => bail!(
                "--channel is required (docs/24 §1.2: no default); \
                 pass --channel official|beta|oem-<customer>"
            ),
            None => "official".to_owned(),
        };
        Ok(Some(Self {
            edition,
            profile,
            channel,
        }))
    }
}

