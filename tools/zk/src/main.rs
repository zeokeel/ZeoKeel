fn load_root(root: &Path) -> Result<RootConfig> {
    let text = fs::read_to_string(root.join("zk.toml")).context("read zk.toml")?;
    let config: RootConfig = toml::from_str(&text).context("parse zk.toml")?;
    if config.schema != 1 {
        bail!("zk.toml schema must be 1, got {}", config.schema);
    }
    Ok(config)
}

fn scan_manifests(root: &Path) -> Result<BTreeMap<String, Manifest>> {
    let mut out = BTreeMap::new();
    let packages_dir = root.join("packages");
    let groups =
        fs::read_dir(&packages_dir).with_context(|| format!("read {}", packages_dir.display()))?;
    for group in groups {
        let group = group?;
        if !group.file_type()?.is_dir() {
            continue;
        }
        for entry in fs::read_dir(group.path())? {
            let entry = entry?;
            if !entry.file_type()?.is_dir() {
                continue;
            }
            let manifest_path = entry.path().join("zk.toml");
            if !manifest_path.is_file() {
                continue;
            }
            let text = fs::read_to_string(&manifest_path)?;
            let manifest: Manifest = toml::from_str(&text)
                .with_context(|| format!("parse {}", manifest_path.display()))?;
            if manifest.schema != 1 {
                bail!("{}: schema must be 1", manifest_path.display());
            }
            if out.insert(manifest.id.clone(), manifest).is_some() {
                bail!("duplicate package id (see {}", manifest_path.display());
            }
        }
    }
    Ok(out)
}

fn load_edition(root: &Path, name: &str) -> Result<EditionFile> {
    let path = root.join("editions").join(format!("{name}.toml"));
    let text = fs::read_to_string(&path).with_context(|| format!("read {}", path.display()))?;
    toml::from_str(&text).with_context(|| format!("parse {}", path.display()))
}

fn resolve_edition(
    root: &Path,
    name: &str,
    chain: &mut Vec<String>,
) -> Result<BTreeMap<String, PackageSel>> {
    if chain.iter().any(|n| n == name) {
        bail!("edition base cycle at {name}");
    }
    chain.push(name.to_owned());
    let file = load_edition(root, name)?;
    let mut packages = match file.edition.base_edition.as_deref() {
        Some(base) => resolve_edition(root, base, chain)?,
        None => BTreeMap::new(),
    };
    if !file.edition.exclude.is_empty() {
        let base_ids: BTreeSet<String> = packages.values().flat_map(PackageSel::ids).collect();
        for excluded in &file.edition.exclude {
            if !base_ids.contains(excluded) {
                bail!("edition {name}: exclude {excluded} not present in base edition closure");
            }
            packages.retain(|_, sel| match sel {
                PackageSel::One(v) => v != excluded,
                PackageSel::Many(v) => {
                    v.retain(|x| x != excluded);
                    !v.is_empty()
                }
            });
        }
    }
    for (role, sel) in file.packages {
        packages.insert(role, sel);
    }
    chain.pop();
    Ok(packages)
}

fn load_profile(root: &Path, name: &str) -> Result<ProfileFile> {
    let path = root.join("profiles").join(format!("{name}.toml"));
    let text = fs::read_to_string(&path).with_context(|| format!("read {}", path.display()))?;
    toml::from_str(&text).with_context(|| format!("parse {}", path.display()))
}

fn resolve_profile(
    root: &Path,
    name: &str,
    packages: &mut BTreeMap<String, PackageSel>,
    chain: &mut Vec<String>,
) -> Result<()> {
    if chain.iter().any(|n| n == name) {
        bail!("profile base cycle at {name}");
    }
    chain.push(name.to_owned());
    let file = load_profile(root, name)?;
    if let Some(base) = file.profile.base.as_deref() {
        resolve_profile(root, base, packages, chain)?;
    }
    for (role, sel) in &file.packages {
        packages.insert(role.clone(), sel.clone());
    }
    for (role, additions) in &file.packages_add {
        let mut current = packages.get(role).map(PackageSel::ids).unwrap_or_default();
        for add in additions {
            if current.iter().any(|x| x == add) {
                bail!("profile {name}: add {add} already present for role {role}");
            }
            current.push(add.clone());
        }
        packages.insert(role.clone(), PackageSel::Many(current));
    }
    for (role, removals) in &file.packages_remove {
        let mut current = packages.get(role).map(PackageSel::ids).unwrap_or_default();
        for remove in removals {
            let before = current.len();
            current.retain(|x| x != remove);
            if current.len() == before {
                bail!("profile {name}: remove {remove} not present for role {role}");
            }
        }
        packages.insert(role.clone(), PackageSel::Many(current));
    }
    chain.pop();
    Ok(())
}

fn load_channel(root: &Path, channel: &str) -> Result<(ChannelFile, PathBuf)> {
    let dir = root.join("brands").join(channel);
    let path = dir.join("channel.json");
    if !path.is_file() {
        bail!("channel {channel} not found at {}", path.display());
    }
    let text = fs::read_to_string(&path).with_context(|| format!("read {}", path.display()))?;
    let file: ChannelFile = serde_json::from_str(&text).with_context(|| format!("parse {}", path.display()))?;
    let display_name = if file.identity.product_name.trim().is_empty() { file.brand.name.trim() } else { file.identity.product_name.trim() };
    if display_name.is_empty() { bail!("channel {channel}: identity.product_name is required"); }
    if !file.identity.slug.is_empty() && !file.identity.slug.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-') { bail!("channel {channel}: bad identity.slug"); }
    if !file.identity.app_id.is_empty() && (!file.identity.app_id.contains('.') || file.identity.app_id.contains(' ')) { bail!("channel {channel}: bad identity.app_id"); }
    if !matches!(file.brand.powered_by.as_str(), "" | "show" | "hide") { bail!("channel {channel}: brand.powered_by must be show|hide"); }
    if file.brand.logo.light.trim().is_empty() || file.brand.logo.dark.trim().is_empty() {
        bail!("channel {channel}: brand.logo.light and brand.logo.dark are required");
    }
    for logo in [&file.brand.logo.light, &file.brand.logo.dark] {
        let logo_path = dir.join(logo);
        if !logo_path.is_file() {
            bail!("channel {channel}: logo file missing: {}", logo_path.display());
        }
    }
    Ok((file, dir))
}

fn resolve(root: &Path, flags: &Flags) -> Result<Resolved> {
    let config = load_root(root)?;
    let manifests = scan_manifests(root)?;
    let (mut channel_file, channel_dir) = load_channel(root, &flags.channel)?;
    if channel_file.brand.name.is_empty() { channel_file.brand.name = channel_file.identity.product_name.clone(); }

    let mut chain = Vec::new();
    let mut packages = resolve_edition(root, &flags.edition, &mut chain)?;
    let mut profile_chain = Vec::new();
    resolve_profile(root, &flags.profile, &mut packages, &mut profile_chain)?;

    validate_contracts(&config, &manifests)?;

    let mut selected = Vec::new();
    let mut by_role: BTreeMap<String, Vec<&PackageSel>> = BTreeMap::new();
    for (role, sel) in &packages {
        by_role.entry(role.clone()).or_default().push(sel);
    }
    for (role, sels) in &by_role {
        let role_def = config
            .roles
            .get(role)
            .with_context(|| format!("role {role} not registered in zk.toml"))?;
        let ids: Vec<String> = sels.iter().flat_map(|s| s.ids()).collect();
        if role_def.cardinality == "singleton" && ids.len() != 1 {
            bail!("role {role} is singleton but has {} providers", ids.len());
        }
        for id in ids {
            let manifest = manifests
                .get(&id)
                .with_context(|| format!("role {role}: package {id} not found"))?;
            let decl = manifest
                .role_decls()
                .into_iter()
                .find(|d| d.name == *role)
                .with_context(|| format!("package {id} does not declare role {role}"))?;
            if decl.contract != role_def.contract {
                bail!(
                    "role {role}: package {id} contract {} != registry {}",
                    decl.contract,
                    role_def.contract
                );
            }
            if decl.cardinality != role_def.cardinality {
                bail!(
                    "role {role}: package {id} cardinality {} != registry {}",
                    decl.cardinality,
                    role_def.cardinality
                );
            }
            if !decl.editions.is_empty() && !decl.editions.iter().any(|e| e == &flags.edition) {
                bail!(
                    "role {role}: package {id} not available for edition {}",
                    flags.edition
                );
            }
            let crate_name = manifest
                .rust_crate()
                .with_context(|| format!("package {id} has no rust facet crate"))?
                .to_owned();
            selected.push(Selected {
                role: role.clone(),
                package_id: id,
                crate_name,
                contract: role_def.contract.clone(),
                cardinality: role_def.cardinality.clone(),
            });
        }
    }

    for selected_pkg in &selected {
        if let Some(manifest) = manifests.get(&selected_pkg.package_id) {
            for required_role in manifest.requires.keys() {
                if !by_role.contains_key(required_role) {
                    bail!(
                        "package {} requires role {required_role} but no provider is selected",
                        manifest.id
                    );
                }
            }
        }
    }

    selected.sort_by(|a, b| a.role.cmp(&b.role));
    Ok(Resolved {
        edition: flags.edition.clone(),
        channel: flags.channel.clone(),
        packages: selected,
        manifests,
        roles: config.roles,
        paths: config.paths,
        brand: channel_file.brand,
        channel_dir,
    })
}

fn validate_contracts(config: &RootConfig, manifests: &BTreeMap<String, Manifest>) -> Result<()> {
    let mut registered: BTreeMap<&str, &str> = BTreeMap::new();
    for (contract_id, crate_name) in &config.contracts {
        let manifest = manifests
            .values()
            .find(|m| m.kind == "contract" && m.rust_crate() == Some(crate_name.as_str()))
            .with_context(|| {
                format!("contract {contract_id}: crate {crate_name} not found among packages")
            })?;
        if registered
            .insert(crate_name.as_str(), contract_id.as_str())
            .is_some()
        {
            bail!("contract crate {crate_name} registered twice");
        }
        if manifest.schema != 1 {
            bail!("contract {}: schema must be 1", manifest.id);
        }
    }
    for (role, def) in &config.roles {
        if !registered.contains_key(def.contract.as_str()) {
            bail!(
                "role {role}: contract {} not registered in [contracts]",
                def.contract
            );
        }
        if def.protected {
            // reserved for OEM checks
        }
    }
    Ok(())
}

fn validate(root: &Path) -> Result<()> {
    let mut flags = Flags {
        edition: "personal".to_owned(),
        profile: "default".to_owned(),
        channel: "official".to_owned(),
    };
    let config = load_root(root)?;
    let manifests = scan_manifests(root)?;
    validate_contracts(&config, &manifests)?;
    for edition in config
        .roles
        .values()
        .flat_map(|r| r.editions.iter())
        .collect::<BTreeSet<_>>()
    {
        flags.edition = (*edition).clone();
        let resolved = resolve(root, &flags)?;
        println!(
            "validate: edition={} profile={} channel={} packages={} roles={}",
            resolved.edition,
            flags.profile,
            resolved.channel,
            resolved.packages.len(),
            resolved.roles.len()
        );
    }
    println!("validate: ok ({} packages scanned)", manifests.len());
    Ok(())
}

fn plan(root: &Path, flags: &Flags) -> Result<()> {
    let resolved = resolve(root, flags)?;
    println!(
        "edition={} profile={} channel={}",
        resolved.edition, flags.profile, resolved.channel
    );
    for pkg in &resolved.packages {
        println!(
            "{:<28} -> {:<24} ({})",
            pkg.role, pkg.package_id, pkg.crate_name
        );
    }
    Ok(())
}

fn compose(root: &Path, flags: &Flags, check: bool) -> Result<()> {
    let resolved = resolve(root, flags)?;
    let mut files: BTreeMap<PathBuf, String> = BTreeMap::new();
    files.insert(
        root.join("crates/zk-composed/Cargo.toml"),
        compose_cargo_toml(root, &resolved)?,
    );
    files.insert(
        root.join("crates/zk-composed/src/lib.rs"),
        compose_lib(&resolved)?,
    );
    for app in ["desktop", "server"] {
        let template = root.join(format!("tools/zk/templates/app_{app}.Cargo.toml"));
        if template.is_file() {
            let content = fs::read_to_string(&template)
                .with_context(|| format!("read {}", template.display()))?;
            files.insert(root.join(format!("apps/{app}/Cargo.toml")), content);
        }
        files.insert(
            root.join(format!("apps/{app}/src/generated/packages.rs")),
            generated_packages_rs(&resolved),
        );
    }
    files.insert(
        root.join("shared/contracts/packages.json"),
        packages_json(&resolved)?,
    );
    files.insert(
        root.join("shared/contracts/roles.json"),
        roles_json(&resolved)?,
    );
    files.insert(
        root.join("docs/generated/PACKAGE-INDEX.md"),
        package_index_md(&resolved),
    );
    // Channel brand assets: authoritative logos come from the channel repo; copy them into the app.
    let light_src = resolved.channel_dir.join(&resolved.brand.logo.light);
    let dark_src = resolved.channel_dir.join(&resolved.brand.logo.dark);
    files.insert(
        root.join("apps/desktop/web/public/brand/logo.svg"),
        fs::read_to_string(&light_src).with_context(|| format!("read {}", light_src.display()))?,
    );
    files.insert(
        root.join("apps/desktop/web/public/brand/logo-dark.svg"),
        fs::read_to_string(&dark_src).with_context(|| format!("read {}", dark_src.display()))?,
    );
    files.insert(
        root.join("apps/desktop/web/src/generated/brand.ts"),
        brand_ts(&resolved),
    );
    files.insert(
        root.join("shared/contracts/brand.json"),
        brand_json(&resolved)?,
    );
    files.insert(
        root.join("apps/desktop/web/src/generated/registry.ts"),
        ui_registry_ts(&resolved),
    );
    if let Some(admin) = admin_registry_ts(&resolved) {
        files.insert(root.join("apps/admin/web/src/generated/registry.ts"), admin);
    }
    files.insert(
        root.join("shared/contracts/ui-contributions.json"),
        ui_contributions_json(&resolved)?,
    );

    if check {
        let mut mismatches = Vec::new();
        for (path, expected) in &files {
            match fs::read_to_string(path) {
                Ok(actual) if actual == *expected => {}
                _ => mismatches.push(path.display().to_string()),
            }
        }
        if !mismatches.is_empty() {
            bail!("generated files differ: {}", mismatches.join(", "));
        }
        println!("compose: up to date ({} files)", files.len());
        return Ok(());
    }
    for (path, content) in &files {
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).with_context(|| format!("mkdir {}", parent.display()))?;
        }
        fs::write(path, content).with_context(|| format!("write {}", path.display()))?;
    }
    println!(
        "compose: wrote {} files (edition={}, channel={})",
        files.len(),
        resolved.edition,
        resolved.channel
    );
    Ok(())
}

fn rel_from_composed(root: &Path, dir: &Path) -> String {
    let rel = dir
        .strip_prefix(root)
        .map(|p| p.to_path_buf())
        .unwrap_or_else(|_| dir.to_path_buf());
    format!("../../{}", rel.display())
}

fn manifest_dir(root: &Path, manifest_id: &str, resolved: &Resolved) -> Result<PathBuf> {
    let manifest = resolved
        .manifests
        .get(manifest_id)
        .with_context(|| format!("manifest {manifest_id}"))?;
    let crate_name = manifest
        .rust_crate()
        .with_context(|| format!("manifest {manifest_id} no rust crate"))?;
    let packages_dir = root.join("packages");
    for group in fs::read_dir(&packages_dir)? {
        let group = group?;
        if !group.file_type()?.is_dir() {
            continue;
        }
        for entry in fs::read_dir(group.path())? {
            let entry = entry?;
            let manifest_path = entry.path().join("zk.toml");
            if !manifest_path.is_file() {
                continue;
            }
            let text = fs::read_to_string(&manifest_path)?;
            let parsed: Manifest = toml::from_str(&text)?;
            if parsed.id == manifest_id {
                let _ = crate_name;
                return Ok(entry.path());
            }
        }
    }
    bail!("dir not found for package {manifest_id}")
}

fn compose_cargo_toml(root: &Path, resolved: &Resolved) -> Result<String> {
    let mut deps: BTreeMap<String, String> = BTreeMap::new();
    for pkg in &resolved.packages {
        let dir = manifest_dir(root, &pkg.package_id, resolved)?;
        deps.insert(pkg.crate_name.clone(), rel_from_composed(root, &dir));
    }
    for manifest in resolved.manifests.values() {
        if manifest.kind == "contract" {
            if let Some(crate_name) = manifest.rust_crate() {
                let dir = manifest_dir(root, &manifest.id, resolved)?;
                deps.insert(crate_name.to_owned(), rel_from_composed(root, &dir));
            }
        }
    }
    let mut out = String::new();
    out.push_str("# @generated by zk compose -- do not edit\n");
    out.push_str("[package]\nname = \"zk-composed\"\nversion.workspace = true\nedition.workspace = true\nlicense.workspace = true\n\n[dependencies]\n");
    for (name, path) in &deps {
        out.push_str(&format!("{name} = {{ path = \"{path}\" }}\n"));
    }
    out.push_str("serde_json = { workspace = true }\n\n[lints]\nworkspace = true\n");
    Ok(out)
}

fn compose_lib(resolved: &Resolved) -> Result<String> {
    let mut tools = Vec::new();
    let mut llm: Option<&Selected> = None;
    let mut agent: Option<&Selected> = None;
    let mut sessions: Option<&Selected> = None;
    let mut settings: Option<&Selected> = None;
    let mut update: Option<&Selected> = None;
    for pkg in &resolved.packages {
        if pkg.role.starts_with("tool.") {
            tools.push(pkg);
        } else if pkg.role == "llm.provider.default" {
            llm = Some(pkg);
        } else if pkg.role == "agent.loop" {
            agent = Some(pkg);
        } else if pkg.role == "store.session" {
            sessions = Some(pkg);
        } else if pkg.role == "store.settings" {
            settings = Some(pkg);
        } else if pkg.role == "update.client" {
            update = Some(pkg);
        } else if pkg.role.starts_with("srv.") || pkg.role.starts_with("admin.") || pkg.role == "auth.client" {
            // Server/admin packages are wired by their composition roots (M2).
        } else if pkg.role == "ui.kit" || pkg.role == "ui.shell" || pkg.role.starts_with("ui.slot.") {
            // UI-only packages are wired by the generated web registry, not the Rust glue.
        } else {
            bail!(
                "compose: role {} has no glue rule in this M0 demo",
                pkg.role
            );
        }
    }
    let llm = llm.context("compose: llm.provider.default is required")?;
    let agent = agent.context("compose: agent.loop is required")?;
    let sessions = sessions.context("compose: store.session is required")?;
    let settings = settings.context("compose: store.settings is required")?;
    let mut out = String::new();
    out.push_str("// @generated by zk compose -- do not edit\n#![forbid(unsafe_code)]\n\nuse std::sync::Arc;\n\n");
    out.push_str(&format!(
        "pub const EDITION: &str = \"{}\";\n",
        resolved.edition
    ));
    out.push_str("pub const PACKAGES: &[&str] = &[");
    for pkg in &resolved.packages {
        out.push_str(&format!("\"{}\",", pkg.package_id));
    }
    out.push_str("];\n\n");
    out.push_str("pub struct Runtime {\n    agent: Arc<dyn zk_contract_agent::Agent>,\n    sessions: Arc<dyn zk_contract_session::SessionStore>,\n    settings: Arc<dyn zk_contract_config::SettingsStore>,\n}\n\n");
    out.push_str("impl Runtime {\n    pub fn run(&self, input: &str) -> Result<serde_json::Value, String> {\n        let reply = self.agent.run(input).map_err(|e| e.to_string())?;\n        serde_json::to_value(reply).map_err(|e| e.to_string())\n    }\n\n    pub fn run_stream(&self, turn_id: &str, input: &str, sink: &dyn zk_contract_agent::EventSink) -> Result<zk_contract_agent::AgentReply, zk_contract_agent::AgentError> {\n        self.agent.run_stream(turn_id, input, sink)\n    }\n\n    pub fn run_stream_in(&self, context: &zk_contract_tool::TurnContext, turn_id: &str, input: &str, sink: &dyn zk_contract_agent::EventSink) -> Result<zk_contract_agent::AgentReply, zk_contract_agent::AgentError> {\n        self.agent.run_stream_in(context, turn_id, input, sink)\n    }\n\n    pub fn sessions(&self) -> Arc<dyn zk_contract_session::SessionStore> {\n        Arc::clone(&self.sessions)\n    }\n\n    pub fn settings(&self) -> Arc<dyn zk_contract_config::SettingsStore> {\n        Arc::clone(&self.settings)\n    }\n\n    pub fn packages(&self) -> &'static [&'static str] {\n        PACKAGES\n    }\n}\n\n");
    if let Some(update_pkg) = update {
        out.push_str(&format!(
            "pub fn check_update(current: &str, platform: &str) -> Result<Option<zk_contract_update::ReleaseInfo>, String> {{\n    {}::check(current, platform).map(|check| if check.available {{ check.release }} else {{ None }}).map_err(|error| error.to_string())\n}}\n\n",
            update_pkg.crate_name.replace('-', "_")
        ));
    } else {
        out.push_str("pub fn check_update(_current: &str, _platform: &str) -> Result<Option<zk_contract_update::ReleaseInfo>, String> { Ok(None) }\n\n");
    }
    if llm.crate_name == "zk-llm-gateway" {
        out.push_str("pub fn configure_llm(base_url: &str, access_token: &str, model: &str) {\n    zk_llm_gateway::set_credentials(base_url, access_token);\n    zk_llm_gateway::set_model(model);\n}\n\npub fn gateway_credentials() -> Option<(String, String)> { zk_llm_gateway::credentials() }\n\n");
    } else {
        out.push_str("pub fn configure_llm(_base_url: &str, _access_token: &str, _model: &str) {}\n\npub fn gateway_credentials() -> Option<(String, String)> { None }\n\n");
    }
    out.push_str("pub fn build() -> Result<Runtime, String> {\n");
    out.push_str("    let tools: Vec<Arc<dyn zk_contract_tool::Tool>> = vec![\n");
    for pkg in &tools {
        out.push_str(&format!(
            "        Arc::new({}::tool()),\n",
            pkg.crate_name.replace('-', "_")
        ));
    }
    out.push_str("    ];\n");
    out.push_str(&format!(
        "    let llm: Arc<dyn zk_contract_llm::LlmProvider> = Arc::new({}::provider());\n",
        llm.crate_name.replace('-', "_")
    ));
    out.push_str(&format!(
        "    let agent: Arc<dyn zk_contract_agent::Agent> = Arc::new({}::agent(tools, llm));\n",
        agent.crate_name.replace('-', "_")
    ));
    out.push_str(&format!(
        "    let sessions: Arc<dyn zk_contract_session::SessionStore> = Arc::new({}::store().map_err(|e| e.to_string())?);\n",
        sessions.crate_name.replace('-', "_")
    ));
    out.push_str(&format!(
        "    let settings: Arc<dyn zk_contract_config::SettingsStore> = Arc::new({}::store());\n",
        settings.crate_name.replace('-', "_")
    ));
    out.push_str("    Ok(Runtime { agent, sessions, settings })\n}\n");
    Ok(out)
}

#[derive(Debug, serde::Deserialize)]
struct OemIndex { #[allow(dead_code)] schema: u32, channels: BTreeMap<String, OemChannel> }
#[derive(Debug, serde::Deserialize)]
struct OemChannel { submodule: String, pin: String, edition: String, depth: String, #[serde(default)] #[allow(dead_code)] owner: String }

fn channel_command(root: &Path, args: &[String]) -> Result<()> {
    match args.first().map(String::as_str).unwrap_or("") {
        "validate" => {
            let mut index_dir: Option<PathBuf> = None;
            let mut i = 1;
            while let Some(arg) = args.get(i) {
                match arg.as_str() {
                    "--index" => { index_dir = args.get(i.saturating_add(1)).map(PathBuf::from); i = i.saturating_add(2); }
                    "--all" => i = i.saturating_add(1),
                    other => bail!("unknown channel validate arg: {other}"),
                }
            }
            let index_dir = index_dir.context("usage: zk channel validate --index <dir> --all")?;
            channel_validate(&index_dir)
        }
        "verify" => {
            let mut channel: Option<String> = None;
            let mut dist: Option<PathBuf> = None;
            let mut i = 1;
            while let Some(arg) = args.get(i) {
                match arg.as_str() {
                    "--channel" => { channel = args.get(i.saturating_add(1)).cloned(); i = i.saturating_add(2); }
                    "--dist" => { dist = args.get(i.saturating_add(1)).map(PathBuf::from); i = i.saturating_add(2); }
                    other => bail!("unknown channel verify arg: {other}"),
                }
            }
            channel_verify(root, &channel.context("--channel")?, &dist.context("--dist")?)
        }
        other => bail!("usage: zk channel <validate|verify> (got {other})"),
    }
}

fn channel_validate(index_dir: &Path) -> Result<()> {
    let index_text = fs::read_to_string(index_dir.join("index.toml")).with_context(|| "read oem index.toml")?;
    let index: OemIndex = toml::from_str(&index_text).context("parse oem index.toml")?;
    let manifest_path = index_dir.join("channels.manifest.json");
    if manifest_path.is_file() {
        let manifest: Vec<String> = serde_json::from_str(&fs::read_to_string(&manifest_path)?).context("parse channels.manifest.json")?;
        let mut expected = manifest;
        let mut actual: Vec<String> = index.channels.keys().cloned().collect();
        expected.sort();
        actual.sort();
        if expected != actual { bail!("channels.manifest.json != index.toml channels"); }
    }
    let mut seen = BTreeMap::<String, String>::new();
    for (id, entry) in &index.channels {
        if id == "official" || id == "beta" || id == "personal" || id == "demo" || id == "test" { bail!("reserved channel id: {id}"); }
        if !id.starts_with("oem-") { bail!("OEM channel must be oem-<customer>: {id}"); }
        if entry.edition != "enterprise" { bail!("channel {id}: edition must be enterprise"); }
        if !matches!(entry.depth.as_str(), "basic" | "deep") { bail!("channel {id}: bad depth"); }
        let customer = index_dir.join(&entry.submodule);
        let channel_text = fs::read_to_string(customer.join("channel.json")).with_context(|| format!("channel {id}: channel.json"))?;
        let actual_pin = sha256_hex(channel_text.as_bytes());
        if actual_pin != entry.pin { bail!("channel {id}: pin mismatch (fixture pin = sha256(channel.json))"); }
        let file: ChannelFile = serde_json::from_str(&channel_text).context("parse channel.json")?;
        let display = if file.identity.product_name.is_empty() { file.brand.name.clone() } else { file.identity.product_name.clone() };
        if display.is_empty() || file.identity.slug.is_empty() || file.identity.app_id.is_empty() { bail!("channel {id}: missing identity fields"); }
        for (value, label) in [(&file.identity.app_id, "app_id"), (&file.identity.deep_link_scheme, "deep_link_scheme"), (&file.identity.app_origin_scheme, "app_origin_scheme"), (&file.identity.data_dir_name, "data_dir_name"), (&file.identity.product_home_dir, "product_home_dir"), (&display, "product_name")] {
            if let Some(previous) = seen.insert(format!("{label}:{value}"), id.clone()) { if previous != *id { bail!("channel uniqueness {label} {value}: {previous} vs {id}"); } }
        }
        if file.identity.deep_link_scheme == file.identity.app_origin_scheme { bail!("channel {id}: deep link and app origin schemes must differ"); }
        if entry.depth == "deep" {
            let packages = customer.join("packages");
            if !packages.is_dir() { bail!("channel {id}: deep requires packages/"); }
        }
        if !customer.join("oem.toml").is_file() { bail!("channel {id}: oem.toml missing"); }
    }
    println!("channel validate ok: {} channels", index.channels.len());
    Ok(())
}

fn channel_verify(root: &Path, channel: &str, dist: &Path) -> Result<()> {
    let (file, _) = load_channel(root, channel)?;
    for name in ["CHANNEL.json", "CLIENT-RELEASE.json", "SHA256SUMS"] {
        if !dist.join(name).is_file() { bail!("dist missing {name}"); }
    }
    if file.brand.powered_by == "hide" {
        let mut stack = vec![dist.to_path_buf()];
        while let Some(dir) = stack.pop() {
            for entry in fs::read_dir(dir)? {
                let path = entry?.path();
                if path.is_dir() { stack.push(path); continue; }
                let name = path.file_name().and_then(|value| value.to_str()).unwrap_or_default();
                if matches!(name, "LICENSE" | "NOTICE" | "CHANNEL.json" | "SHA256SUMS") { continue; }
                if let Ok(text) = fs::read_to_string(&path) { if text.contains("ZeoKeel") { bail!("brand residue in {}", path.display()); } }
            }
        }
    }
    println!("channel verify ok: {channel}");
    Ok(())
}

fn sha256_hex(bytes: &[u8]) -> String {
    use sha2::{Digest, Sha256};
    let mut hash = Sha256::new();
    hash.update(bytes);
    format!("{:x}", hash.finalize())
}

fn db_lock(root: &Path, check: bool) -> Result<()> {
    use sha2::{Digest, Sha256};
    #[derive(serde::Serialize)]
    struct LockMigration { version: String, package: String, checksum: String }
    #[derive(serde::Serialize)]
    struct LockFile { schema: u32, migrations: Vec<LockMigration> }

    fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, String, String)>) -> Result<()> {
        if !dir.is_dir() { return Ok(()); }
        for entry in fs::read_dir(dir)? {
            let entry = entry?;
            let path = entry.path();
            if path.is_dir() {
                collect(root, &path, out)?;
                continue;
            }
            if path.extension().and_then(|value| value.to_str()) != Some("sql") {
                continue;
            }
            let file_name = path.file_name().and_then(|value| value.to_str()).unwrap_or_default();
            let version = file_name.trim_end_matches(".sql").to_owned();
            let package = path.strip_prefix(root).map(|value| value.to_string_lossy().replace('\\', "/")).unwrap_or_default();
            let content = fs::read(&path)?;
            let mut hash = Sha256::new();
            hash.update(&content);
            out.push((version, package, format!("{:x}", hash.finalize())));
        }
        Ok(())
    }

    let mut migrations = Vec::new();
    collect(root, &root.join("packages"), &mut migrations)?;
    migrations.sort_by(|a, b| a.0.cmp(&b.0));
    let mut seen = BTreeSet::new();
    for (version, _, _) in &migrations {
        if !seen.insert(version.clone()) {
            bail!("duplicate migration version: {version}");
        }
    }
    let lock = LockFile {
        schema: 1,
        migrations: migrations.into_iter().map(|(version, package, checksum)| LockMigration { version, package, checksum }).collect(),
    };
    let rendered = format!("{}\n", serde_json::to_string_pretty(&lock)?);
    let path = root.join("zk.lock");
    if check {
        let current = fs::read_to_string(&path).with_context(|| "zk.lock missing; run zk db lock")?;
        if current != rendered {
            bail!("zk.lock out of date; run zk db lock");
        }
        println!("db lock: up to date ({} migrations)", lock.migrations.len());
        return Ok(());
    }
    fs::write(&path, rendered)?;
    println!("db lock: wrote {} migrations", lock.migrations.len());
    Ok(())
}

