    fn word(index: usize) -> String {
        let mut value = index;
        let mut out = String::new();
        loop {
            let letter = u8::try_from(value % 26).unwrap_or(0).saturating_add(b'a');
            out.insert(0, char::from(letter));
            value /= 26;
            if value == 0 {
                break;
            }
        }
        out
    }

