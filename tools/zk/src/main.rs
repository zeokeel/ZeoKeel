fn validate(root: &Path) -> Result<()> {
    let mut flags = Flags {
        edition: "personal".to_owned(),
        profile: "default".to_owned(),
        channel: "official".to_owned(),
    };
    let config = load_root(root)?;
    let manifests = scan_manifests(root)?;
    validate_contracts(&config, &manifests)?;
    let personal_only = load_personal_only(root, &config)?;
    for edition in config
        .roles
        .values()
        .flat_map(|r| r.editions.iter())
        .collect::<BTreeSet<_>>()
    {
        flags.edition = (*edition).clone();
        let resolved = resolve(root, &flags)?;
        if !flags.edition.starts_with("personal") {
            let leaked: Vec<&str> = resolved
                .packages
                .iter()
                .filter(|pkg| personal_only.iter().any(|id| id == &pkg.package_id))
                .map(|pkg| pkg.package_id.as_str())
                .collect();
            if !leaked.is_empty() {
                bail!(
                    "edition {} contains personal-only packages (docs/24 §1.1): {}",
                    flags.edition,
                    leaked.join(", ")
                );
            }
        }
        println!(
            "validate: edition={} profile={} channel={} packages={} roles={}",
            resolved.edition,
            flags.profile,
            resolved.channel,
            resolved.packages.len(),
            resolved.roles.len()
        );
    }
    println!("validate: ok ({} packages scanned)", manifests.len());
    Ok(())
}

fn plan(root: &Path, flags: &Flags) -> Result<()> {
    let resolved = resolve(root, flags)?;
    println!(
        "edition={} profile={} channel={}",
        resolved.edition, flags.profile, resolved.channel
    );
    for pkg in &resolved.packages {
        println!(
            "{:<28} -> {:<24} ({})",
            pkg.role, pkg.package_id, pkg.crate_name
        );
    }
    Ok(())
}

fn docs(root: &Path, check: bool) -> Result<()> {
    let config = load_root(root)?;
    let manifests = scan_manifests(root)?;
    validate_contracts(&config, &manifests)?;
    let contract_md = contract_index_md(&config, &manifests);
    let matrix_md = profile_matrix_md(root, &config)?;
    let dir = root.join(&config.paths.docs_generated);
    let files: [(PathBuf, String); 2] = [
        (dir.join("CONTRACT-INDEX.md"), contract_md),
        (dir.join("PROFILE-MATRIX.md"), matrix_md),
    ];
    if check {
        let mut mismatched: Vec<String> = Vec::new();
        for (path, expected) in &files {
            match fs::read_to_string(path) {
                Ok(actual) if actual == *expected => {}
                _ => mismatched.push(path.display().to_string()),
            }
        }
        if !mismatched.is_empty() {
            bail!(
                "docs differ: {}; run `zk docs` to regenerate (docs/24 §3)",
                mismatched.join(", ")
            );
        }
        println!("docs: up to date ({} files)", files.len());
        return Ok(());
    }
    fs::create_dir_all(&dir)?;
    for (path, content) in &files {
        fs::write(path, content).with_context(|| format!("write {}", path.display()))?;
    }
    println!("docs: wrote {} files to {}", files.len(), dir.display());
    Ok(())
}

fn list_named_toml(root: &Path, dir: &str, marker: &str) -> Result<Vec<String>> {
    let base = root.join(dir);
    if !base.is_dir() {
        return Ok(Vec::new());
    }
    let mut names: Vec<String> = Vec::new();
    for entry in fs::read_dir(&base)? {
        let entry = entry?;
        let path = entry.path();
        if path.extension().and_then(|ext| ext.to_str()) != Some("toml") {
            continue;
        }
        let text = fs::read_to_string(&path)?;
        if !text.contains(marker) {
            continue;
        }
        if let Some(stem) = path.file_stem().and_then(|stem| stem.to_str()) {
            names.push(stem.to_owned());
        }
    }
    names.sort();
    Ok(names)
}

fn list_editions(root: &Path) -> Result<Vec<String>> {
    list_named_toml(root, "editions", "[edition]")
}

fn list_profiles(root: &Path) -> Result<Vec<String>> {
    list_named_toml(root, "profiles", "[profile]")
}

fn list_channels(root: &Path) -> Result<Vec<String>> {
    let base = root.join("brands");
    if !base.is_dir() {
        return Ok(Vec::new());
    }
    let mut names: Vec<String> = Vec::new();
    for entry in fs::read_dir(&base)? {
        let entry = entry?;
        if !entry.file_type()?.is_dir() {
            continue;
        }
        if !entry.path().join("channel.json").is_file() {
            continue;
        }
        names.push(entry.file_name().to_string_lossy().to_string());
    }
    names.sort();
    Ok(names)
}

fn contract_index_md(config: &RootConfig, manifests: &BTreeMap<String, Manifest>) -> String {
    let mut output = String::new();
    output.push_str("<!-- @generated by zk docs -- do not edit -->\n\n# Contract Index\n\n");
    output.push_str(&format!(
        "_{} contracts · {} packages scanned · crate ↔ contract is the [contracts] map (docs/24 §2.1)_\n\n",
        config.contracts.len(),
        manifests.len()
    ));
    output.push_str(
        "| contract | crate | roles (editions) | implementing packages |\n| --- | --- | --- | --- |\n",
    );
    for (contract_id, crate_name) in &config.contracts {
        let mut roles: Vec<&String> = config
            .roles
            .iter()
            .filter(|(_, def)| def.contract == *crate_name)
            .map(|(role, _)| role)
            .collect();
        roles.sort();
        let mut implementers: BTreeSet<&str> = BTreeSet::new();
        for manifest in manifests.values() {
            for decl in manifest.role_decls() {
                if roles.iter().any(|role| **role == decl.name) {
                    implementers.insert(manifest.id.as_str());
                }
            }
        }
        let roles_cell = if roles.is_empty() {
            "-".to_owned()
        } else {
            roles
                .iter()
                .map(|role| match config.roles.get(*role) {
                    Some(def) if !def.editions.is_empty() => {
                        format!("`{role}` ({})", def.editions.join(", "))
                    }
                    _ => format!("`{role}`"),
                })
                .collect::<Vec<String>>()
                .join(", ")
        };
        let implementers_cell = if implementers.is_empty() {
            "-".to_owned()
        } else {
            implementers
                .iter()
                .map(|id| format!("`{id}`"))
                .collect::<Vec<String>>()
                .join(", ")
        };
        output.push_str(&format!(
            "| `{contract_id}` | `{crate_name}` | {roles_cell} | {implementers_cell} |\n"
        ));
    }
    output
}

fn profile_matrix_md(root: &Path, config: &RootConfig) -> Result<String> {
    let editions = list_editions(root)?;
    let profiles = list_profiles(root)?;
    let channels = list_channels(root)?;
    let personal_only = load_personal_only(root, config)?;
    let mut personal_baseline: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for channel in &channels {
        let flags = Flags {
            edition: "personal".to_owned(),
            profile: "default".to_owned(),
            channel: channel.clone(),
        };
        if let Ok(resolved) = resolve(root, &flags) {
            personal_baseline.insert(
                channel.clone(),
                resolved
                    .packages
                    .iter()
                    .map(|pkg| pkg.package_id.clone())
                    .collect(),
            );
        }
    }
    let mut output = String::new();
    output.push_str("<!-- @generated by zk docs -- do not edit -->\n\n# Profile Matrix\n\n");
    output.push_str(&format!(
        "_{} editions × {} profiles × {} channels. Committed baseline is personal×default×official (docs/24 §1.2); \
         `excluded_from_personal` compares the row with personal×default×<channel>._\n\n",
        editions.len(),
        profiles.len(),
        channels.len()
    ));
    output.push_str(
        "| edition | profile | channel | status | packages | generated EDITION | personal_only_hits | excluded_from_personal |\n\
         | --- | --- | --- | --- | --- | --- | --- | --- |\n",
    );
    for edition in &editions {
        for profile in &profiles {
            for channel in &channels {
                let flags = Flags {
                    edition: edition.clone(),
                    profile: profile.clone(),
                    channel: channel.clone(),
                };
                match resolve(root, &flags) {
                    Ok(resolved) => {
                        let ids: Vec<&str> = resolved
                            .packages
                            .iter()
                            .map(|pkg| pkg.package_id.as_str())
                            .collect();
                        let hits = ids
                            .iter()
                            .filter(|id| personal_only.iter().any(|known| known.as_str() == **id))
                            .count();
                        let excluded = personal_baseline
                            .get(channel.as_str())
                            .map(|baseline| {
                                baseline
                                    .iter()
                                    .filter(|id| !ids.contains(&id.as_str()))
                                    .count()
                            })
                            .unwrap_or(0);
                        let status = if resolved.edition != *edition {
                            "ERROR edition".to_owned()
                        } else if hits > 0 && edition != "personal" {
                            format!("ERROR personal-only leak ({hits})")
                        } else {
                            "ok".to_owned()
                        };
                        output.push_str(&format!(
                            "| `{edition}` | `{profile}` | `{channel}` | {status} | {} | `{}` | {} | {} |\n",
                            resolved.packages.len(),
                            resolved.edition,
                            hits,
                            excluded
                        ));
                    }
                    Err(error) => {
                        let message = error.to_string().replace('\n', " ").replace('|', "/");
                        output.push_str(&format!(
                            "| `{edition}` | `{profile}` | `{channel}` | error: {message} | - | - | - | - |\n"
                        ));
                    }
                }
            }
        }
    }
    Ok(output)
}

fn compose_files(root: &Path, resolved: &Resolved) -> Result<BTreeMap<PathBuf, String>> {
    let mut files: BTreeMap<PathBuf, String> = BTreeMap::new();
    files.insert(
        root.join("crates/zk-composed/Cargo.toml"),
        compose_cargo_toml(root, resolved)?,
    );
    files.insert(
        root.join("crates/zk-composed/src/lib.rs"),
        compose_lib(root, resolved)?,
    );
    let server_target = resolved.targets.iter().any(|target| target == "server");
    for app in ["desktop", "server"] {
        if app == "server" && !server_target {
            // R8.2/F6: personal edition targets = ["desktop"]; do not generate the
            // server-domain product glue/manifest. The workspace stays buildable
            // because the trimmed manifest has no srv-* dependencies and main is a
            // generated stub (full server is regenerated for enterprise compose).
            let template = root.join("tools/zk/templates/app_server_trimmed.Cargo.toml");
            files.insert(
                root.join("apps/server/Cargo.toml"),
                fs::read_to_string(&template)
                    .with_context(|| format!("read {}", template.display()))?,
            );
            files.insert(root.join("apps/server/src/main.rs"), trimmed_server_main());
            files.insert(
                root.join("apps/server/src/generated/packages.rs"),
                generated_packages_rs_trimmed(resolved),
            );
            continue;
        }
        let template = root.join(format!("tools/zk/templates/app_{app}.Cargo.toml"));
        if template.is_file() {
            let content = fs::read_to_string(&template)
                .with_context(|| format!("read {}", template.display()))?;
            files.insert(root.join(format!("apps/{app}/Cargo.toml")), content);
        }
        if app == "server" {
            let template = root.join("tools/zk/templates/app_server.main.rs");
            files.insert(
                root.join("apps/server/src/main.rs"),
                fs::read_to_string(&template)
                    .with_context(|| format!("read {}", template.display()))?,
            );
        }
        files.insert(
            root.join(format!("apps/{app}/src/generated/packages.rs")),
            generated_packages_rs(resolved),
        );
    }
    files.insert(
        root.join("shared/contracts/packages.json"),
        packages_json(resolved)?,
    );
    files.insert(
        root.join("shared/contracts/roles.json"),
        roles_json(resolved)?,
    );
    files.insert(
        root.join("docs/generated/PACKAGE-INDEX.md"),
        package_index_md(resolved),
    );
    // Channel brand assets: authoritative logos come from the channel repo; copy them into the app.
    let light_src = resolved.channel_dir.join(&resolved.brand.logo.light);
    let dark_src = resolved.channel_dir.join(&resolved.brand.logo.dark);
    files.insert(
        root.join("apps/desktop/web/public/brand/logo.svg"),
        fs::read_to_string(&light_src).with_context(|| format!("read {}", light_src.display()))?,
    );
    files.insert(
        root.join("apps/desktop/web/public/brand/logo-dark.svg"),
        fs::read_to_string(&dark_src).with_context(|| format!("read {}", dark_src.display()))?,
    );
    files.insert(
        root.join("apps/desktop/web/src/generated/brand.ts"),
        brand_ts(resolved, &desktop_version(root)?),
    );
    files.insert(
        root.join("shared/contracts/brand.json"),
        brand_json(resolved)?,
    );
    files.insert(
        root.join("apps/desktop/web/src/generated/registry.ts"),
        ui_registry_ts(resolved),
    );
    files.insert(
        root.join("apps/admin/web/src/generated/registry.ts"),
        admin_registry_ts(resolved),
    );
    files.insert(
        root.join("shared/contracts/ui-contributions.json"),
        ui_contributions_json(resolved)?,
    );

    Ok(files)
}

fn compose(root: &Path, flags: &Flags, check: bool) -> Result<()> {
    let resolved = resolve(root, flags)?;
    let files = compose_files(root, &resolved)?;
    if check {
        // Only the committed baseline (personal×default×official, docs/24 §1.2) is
        // drift-checked against the working tree. Non-baseline editions are composed
        // by CI/build scripts before building and are never committed.
        if resolved.edition != "personal"
            || resolved.channel != "official"
            || flags.profile != "default"
        {
            bail!(
                "compose --check only validates the committed baseline personal×default×official; \
                 use `compose --edition {edition} --profile {profile} --channel {channel}` to build a non-baseline artifact",
                edition = resolved.edition,
                profile = flags.profile,
                channel = resolved.channel
            );
        }
        let mut mismatches = Vec::new();
        for (path, expected) in &files {
            match fs::read_to_string(path) {
                Ok(actual) if actual == *expected => {}
                _ => mismatches.push(path.display().to_string()),
            }
        }
        if !mismatches.is_empty() {
            bail!("generated files differ: {}", mismatches.join(", "));
        }
        println!("compose: up to date ({} files)", files.len());
        return Ok(());
    }
    for (path, content) in &files {
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).with_context(|| format!("mkdir {}", parent.display()))?;
        }
        fs::write(path, content).with_context(|| format!("write {}", path.display()))?;
    }
    println!(
        "compose: wrote {} files (edition={}, channel={})",
        files.len(),
        resolved.edition,
        resolved.channel
    );
    Ok(())
}

fn rel_from_composed(root: &Path, dir: &Path) -> String {
    let rel = dir
        .strip_prefix(root)
        .map(|p| p.to_path_buf())
        .unwrap_or_else(|_| dir.to_path_buf());
    // Emit forward slashes even when `zk compose` runs on Windows: the value becomes a
    // TOML/JSON string in generated manifests, and `\` starts an invalid TOML escape
    // (cargo metadata then fails on Windows release builds).
    let rel = rel.to_string_lossy().replace('\\', "/");
    format!("../../{rel}")
}

fn find_package_dir(root: &Path, manifest_id: &str) -> Result<PathBuf> {
    let packages_dir = root.join("packages");
    for group in fs::read_dir(&packages_dir)? {
        let group = group?;
        if !group.file_type()?.is_dir() {
            continue;
        }
        for entry in fs::read_dir(group.path())? {
            let entry = entry?;
            if !entry.file_type()?.is_dir() {
                continue;
            }
            let manifest_path = entry.path().join("zk.toml");
            if !manifest_path.is_file() {
                continue;
            }
            let text = fs::read_to_string(&manifest_path)?;
            let parsed: Manifest = toml::from_str(&text)?;
            if parsed.id == manifest_id {
                return Ok(entry.path());
            }
        }
    }
    bail!("dir not found for package {manifest_id}")
}

fn manifest_dir(root: &Path, manifest_id: &str, resolved: &Resolved) -> Result<PathBuf> {
    if !resolved.manifests.contains_key(manifest_id) {
        bail!("manifest {manifest_id}");
    }
    find_package_dir(root, manifest_id)
}

fn compose_cargo_toml(root: &Path, resolved: &Resolved) -> Result<String> {
    let mut deps: BTreeMap<String, String> = BTreeMap::new();
    for pkg in &resolved.packages {
        let dir = manifest_dir(root, &pkg.package_id, resolved)?;
        deps.insert(pkg.crate_name.clone(), rel_from_composed(root, &dir));
    }
    for manifest in resolved.manifests.values() {
        if manifest.kind == "contract" {
            if let Some(crate_name) = manifest.rust_crate() {
                let dir = manifest_dir(root, &manifest.id, resolved)?;
                deps.insert(crate_name.to_owned(), rel_from_composed(root, &dir));
            }
        }
    }
    let mut out = String::new();
    out.push_str("# @generated by zk compose -- do not edit\n");
    out.push_str("[package]\nname = \"zk-composed\"\nversion.workspace = true\nedition.workspace = true\nlicense.workspace = true\n\n[dependencies]\n");
    for (name, path) in &deps {
        out.push_str(&format!("{name} = {{ path = \"{path}\" }}\n"));
    }
    // Personal embedding/media glue builds rig models via the shared media kit.
    if resolved.edition == "personal"
        && resolved.packages.iter().any(|pkg| {
            pkg.crate_name == "zk-cap-vector"
                || matches!(
                    pkg.role.as_str(),
                    "media.image" | "media.audio" | "media.transcription" | "media.rerank"
                )
        })
    {
        out.push_str("zk-kit-media = { path = \"../../crates/zk-kit-media\" }\n");
    }
    out.push_str("serde_json = { workspace = true }\nrig-core = { workspace = true }\n\n[lints]\nworkspace = true\n");
    // CLI-only dep audit triage: rig-core is consumed by the embedding/media glue
    // generated in this crate's lib.rs; cargo-machete cannot see that dependency edge.
    out.push_str("\n[package.metadata.cargo-machete]\nignored = [\"rig-core\"]\n");
    Ok(out)
}

