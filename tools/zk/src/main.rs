#![forbid(unsafe_code)]
//! ZeoKeel `zk` composition CLI (minimal M0 subset).
//!
//! Commands: `validate`, `compose [--check]`, `plan`, `capability [--check]`,
//! `find <kw>`, `lint [--duplicates]`.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{bail, Context, Result};
use serde::{Deserialize, Serialize};

const GENERATED: &str = "@generated by zk compose -- do not edit";

fn main() {
    if let Err(err) = run() {
        eprintln!("zk: {err:#}");
        std::process::exit(1);
    }
}

fn run() -> Result<()> {
    let mut args = std::env::args().skip(1);
    let command = args
        .next()
        .context("usage: zk <validate|compose|plan|capability|find|lint>")?;
    let root = find_root()?;
    let rest: Vec<String> = args.collect();
    match command.as_str() {
        "validate" => validate(&root),
        "compose" => {
            let flags = Flags::parse(&rest)?.context("compose requires --edition")?;
            let check = rest.iter().any(|a| a == "--check");
            compose(&root, &flags, check)
        }
        "plan" => {
            let flags =
                Flags::parse(&rest)?.context("plan requires --edition/--profile/--channel")?;
            plan(&root, &flags)
        }
        "capability" => {
            let check = rest.iter().any(|a| a == "--check");
            capability(&root, check)
        }
        "find" => {
            let keyword = rest.first().context("usage: zk find <keyword>")?.clone();
            find(&root, &keyword)
        }
        "lint" => lint(&root, rest.iter().any(|a| a == "--duplicates")),
        other => bail!("unknown command: {other}"),
    }
}

fn find_root() -> Result<PathBuf> {
    let mut dir = std::env::current_dir().context("current_dir")?;
    loop {
        if dir.join("zk.toml").is_file() {
            return Ok(dir);
        }
        if !dir.pop() {
            bail!("zk.toml not found (run from the repo)");
        }
    }
}

#[derive(Debug, Clone)]
struct Flags {
    edition: String,
    profile: String,
    channel: String,
}

impl Flags {
    fn parse(args: &[String]) -> Result<Option<Self>> {
        let mut map: BTreeMap<&str, String> = BTreeMap::new();
        let mut i = 0;
        while let Some(arg) = args.get(i) {
            let key = match arg.as_str() {
                "--edition" => "--edition",
                "--profile" => "--profile",
                "--channel" => "--channel",
                _ => {
                    i += 1;
                    continue;
                }
            };
            let value = args
                .get(i + 1)
                .with_context(|| format!("{key} needs a value"))?;
            map.insert(key, value.clone());
            i += 2;
        }
        let edition = match map.get("--edition") {
            Some(v) => v.clone(),
            None => return Ok(None),
        };
        let profile = map
            .get("--profile")
            .cloned()
            .unwrap_or_else(|| "default".to_owned());
        let channel = map
            .get("--channel")
            .cloned()
            .unwrap_or_else(|| "official".to_owned());
        Ok(Some(Self {
            edition,
            profile,
            channel,
        }))
    }
}

#[derive(Debug, Deserialize)]
struct RootConfig {
    schema: u32,
    #[serde(default)]
    paths: Paths,
    roles: BTreeMap<String, RoleDef>,
    contracts: BTreeMap<String, String>,
}

#[derive(Debug, Clone, Deserialize)]
struct Paths {
    #[serde(default = "default_crates")]
    crates: String,
    #[serde(default = "default_shared")]
    shared: String,
    #[serde(default = "default_docs_generated")]
    docs_generated: String,
}

impl Default for Paths {
    fn default() -> Self {
        Self {
            crates: default_crates(),
            shared: default_shared(),
            docs_generated: default_docs_generated(),
        }
    }
}
fn default_crates() -> String {
    "crates".to_owned()
}
fn default_shared() -> String {
    "shared".to_owned()
}
fn default_docs_generated() -> String {
    "docs/generated".to_owned()
}

#[derive(Debug, Clone, Deserialize)]
struct RoleDef {
    contract: String,
    cardinality: String,
    #[serde(default)]
    editions: Vec<String>,
    #[serde(default)]
    protected: bool,
}

#[derive(Debug, Clone, Deserialize)]
struct Manifest {
    schema: u32,
    id: String,
    kind: String,
    version: String,
    #[serde(default)]
    summary: String,
    #[serde(default)]
    role: Option<RoleDecl>,
    #[serde(default)]
    roles: Vec<RoleDecl>,
    #[serde(default)]
    facets: Facets,
    #[serde(default)]
    requires: BTreeMap<String, String>,
}

impl Manifest {
    fn role_decls(&self) -> Vec<&RoleDecl> {
        let mut out: Vec<&RoleDecl> = Vec::new();
        if let Some(role) = self.role.as_ref() {
            out.push(role);
        }
        out.extend(self.roles.iter());
        out
    }

    fn rust_crate(&self) -> Option<&str> {
        self.facets.rust.as_ref().map(|r| r.crate_name.as_str())
    }
}

#[derive(Debug, Clone, Deserialize)]
struct RoleDecl {
    name: String,
    contract: String,
    cardinality: String,
    #[serde(default)]
    editions: Vec<String>,
}

#[derive(Debug, Clone, Default, Deserialize)]
struct Facets {
    #[serde(default)]
    rust: Option<RustFacet>,
}

#[derive(Debug, Clone, Deserialize)]
struct RustFacet {
    #[serde(rename = "crate")]
    crate_name: String,
}

#[derive(Debug, Deserialize)]
struct EditionFile {
    edition: EditionDecl,
    #[serde(default)]
    packages: BTreeMap<String, PackageSel>,
}

#[derive(Debug, Deserialize)]
struct EditionDecl {
    #[allow(dead_code)]
    name: String,
    #[serde(default)]
    base_edition: Option<String>,
    #[serde(default)]
    exclude: Vec<String>,
    #[serde(default)]
    targets: Vec<String>,
}

#[derive(Debug, Deserialize)]
struct ProfileFile {
    profile: ProfileDecl,
    #[serde(default)]
    packages: BTreeMap<String, PackageSel>,
    #[serde(default)]
    packages_add: BTreeMap<String, Vec<String>>,
    #[serde(default)]
    packages_remove: BTreeMap<String, Vec<String>>,
}

#[derive(Debug, Deserialize)]
struct ProfileDecl {
    #[allow(dead_code)]
    name: String,
    #[serde(default)]
    base: Option<String>,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(untagged)]
enum PackageSel {
    One(String),
    Many(Vec<String>),
}

impl PackageSel {
    fn ids(&self) -> Vec<String> {
        match self {
            Self::One(v) => vec![v.clone()],
            Self::Many(v) => v.clone(),
        }
    }
}

#[derive(Debug, Clone)]
struct Selected {
    role: String,
    package_id: String,
    crate_name: String,
    contract: String,
    cardinality: String,
}

#[derive(Debug, Clone)]
struct Resolved {
    edition: String,
    channel: String,
    packages: Vec<Selected>,
    manifests: BTreeMap<String, Manifest>,
    roles: BTreeMap<String, RoleDef>,
    paths: Paths,
}

fn load_root(root: &Path) -> Result<RootConfig> {
    let text = fs::read_to_string(root.join("zk.toml")).context("read zk.toml")?;
    let config: RootConfig = toml::from_str(&text).context("parse zk.toml")?;
    if config.schema != 1 {
        bail!("zk.toml schema must be 1, got {}", config.schema);
    }
    Ok(config)
}

fn scan_manifests(root: &Path) -> Result<BTreeMap<String, Manifest>> {
    let mut out = BTreeMap::new();
    let packages_dir = root.join("packages");
    let groups =
        fs::read_dir(&packages_dir).with_context(|| format!("read {}", packages_dir.display()))?;
    for group in groups {
        let group = group?;
        if !group.file_type()?.is_dir() {
            continue;
        }
        for entry in fs::read_dir(group.path())? {
            let entry = entry?;
            if !entry.file_type()?.is_dir() {
                continue;
            }
            let manifest_path = entry.path().join("zk.toml");
            if !manifest_path.is_file() {
                continue;
            }
            let text = fs::read_to_string(&manifest_path)?;
            let manifest: Manifest = toml::from_str(&text)
                .with_context(|| format!("parse {}", manifest_path.display()))?;
            if manifest.schema != 1 {
                bail!("{}: schema must be 1", manifest_path.display());
            }
            if out.insert(manifest.id.clone(), manifest).is_some() {
                bail!("duplicate package id (see {}", manifest_path.display());
            }
        }
    }
    Ok(out)
}

fn load_edition(root: &Path, name: &str) -> Result<EditionFile> {
    let path = root.join("editions").join(format!("{name}.toml"));
    let text = fs::read_to_string(&path).with_context(|| format!("read {}", path.display()))?;
    toml::from_str(&text).with_context(|| format!("parse {}", path.display()))
}

fn resolve_edition(
    root: &Path,
    name: &str,
    chain: &mut Vec<String>,
) -> Result<BTreeMap<String, PackageSel>> {
    if chain.iter().any(|n| n == name) {
        bail!("edition base cycle at {name}");
    }
    chain.push(name.to_owned());
    let file = load_edition(root, name)?;
    let mut packages = match file.edition.base_edition.as_deref() {
        Some(base) => resolve_edition(root, base, chain)?,
        None => BTreeMap::new(),
    };
    if !file.edition.exclude.is_empty() {
        let base_ids: BTreeSet<String> = packages.values().flat_map(PackageSel::ids).collect();
        for excluded in &file.edition.exclude {
            if !base_ids.contains(excluded) {
                bail!("edition {name}: exclude {excluded} not present in base edition closure");
            }
            packages.retain(|_, sel| match sel {
                PackageSel::One(v) => v != excluded,
                PackageSel::Many(v) => {
                    v.retain(|x| x != excluded);
                    !v.is_empty()
                }
            });
        }
    }
    for (role, sel) in file.packages {
        packages.insert(role, sel);
    }
    chain.pop();
    Ok(packages)
}

fn load_profile(root: &Path, name: &str) -> Result<ProfileFile> {
    let path = root.join("profiles").join(format!("{name}.toml"));
    let text = fs::read_to_string(&path).with_context(|| format!("read {}", path.display()))?;
    toml::from_str(&text).with_context(|| format!("parse {}", path.display()))
}

fn resolve_profile(
    root: &Path,
    name: &str,
    packages: &mut BTreeMap<String, PackageSel>,
    chain: &mut Vec<String>,
) -> Result<()> {
    if chain.iter().any(|n| n == name) {
        bail!("profile base cycle at {name}");
    }
    chain.push(name.to_owned());
    let file = load_profile(root, name)?;
    if let Some(base) = file.profile.base.as_deref() {
        resolve_profile(root, base, packages, chain)?;
    }
    for (role, sel) in &file.packages {
        packages.insert(role.clone(), sel.clone());
    }
    for (role, additions) in &file.packages_add {
        let mut current = packages.get(role).map(PackageSel::ids).unwrap_or_default();
        for add in additions {
            if current.iter().any(|x| x == add) {
                bail!("profile {name}: add {add} already present for role {role}");
            }
            current.push(add.clone());
        }
        packages.insert(role.clone(), PackageSel::Many(current));
    }
    for (role, removals) in &file.packages_remove {
        let mut current = packages.get(role).map(PackageSel::ids).unwrap_or_default();
        for remove in removals {
            let before = current.len();
            current.retain(|x| x != remove);
            if current.len() == before {
                bail!("profile {name}: remove {remove} not present for role {role}");
            }
        }
        packages.insert(role.clone(), PackageSel::Many(current));
    }
    chain.pop();
    Ok(())
}

fn channel_file(root: &Path, channel: &str) -> Result<PathBuf> {
    let path = root.join("brands").join(channel).join("channel.json");
    if !path.is_file() {
        bail!("channel {channel} not found at {}", path.display());
    }
    Ok(path)
}

fn resolve(root: &Path, flags: &Flags) -> Result<Resolved> {
    let config = load_root(root)?;
    let manifests = scan_manifests(root)?;
    channel_file(root, &flags.channel)?;

    let mut chain = Vec::new();
    let mut packages = resolve_edition(root, &flags.edition, &mut chain)?;
    let mut profile_chain = Vec::new();
    resolve_profile(root, &flags.profile, &mut packages, &mut profile_chain)?;

    validate_contracts(&config, &manifests)?;

    let mut selected = Vec::new();
    let mut by_role: BTreeMap<String, Vec<&PackageSel>> = BTreeMap::new();
    for (role, sel) in &packages {
        by_role.entry(role.clone()).or_default().push(sel);
    }
    for (role, sels) in &by_role {
        let role_def = config
            .roles
            .get(role)
            .with_context(|| format!("role {role} not registered in zk.toml"))?;
        let ids: Vec<String> = sels.iter().flat_map(|s| s.ids()).collect();
        if role_def.cardinality == "singleton" && ids.len() != 1 {
            bail!("role {role} is singleton but has {} providers", ids.len());
        }
        for id in ids {
            let manifest = manifests
                .get(&id)
                .with_context(|| format!("role {role}: package {id} not found"))?;
            let decl = manifest
                .role_decls()
                .into_iter()
                .find(|d| d.name == *role)
                .with_context(|| format!("package {id} does not declare role {role}"))?;
            if decl.contract != role_def.contract {
                bail!(
                    "role {role}: package {id} contract {} != registry {}",
                    decl.contract,
                    role_def.contract
                );
            }
            if decl.cardinality != role_def.cardinality {
                bail!(
                    "role {role}: package {id} cardinality {} != registry {}",
                    decl.cardinality,
                    role_def.cardinality
                );
            }
            if !decl.editions.is_empty() && !decl.editions.iter().any(|e| e == &flags.edition) {
                bail!(
                    "role {role}: package {id} not available for edition {}",
                    flags.edition
                );
            }
            let crate_name = manifest
                .rust_crate()
                .with_context(|| format!("package {id} has no rust facet crate"))?
                .to_owned();
            selected.push(Selected {
                role: role.clone(),
                package_id: id,
                crate_name,
                contract: role_def.contract.clone(),
                cardinality: role_def.cardinality.clone(),
            });
        }
    }

    for selected_pkg in &selected {
        if let Some(manifest) = manifests.get(&selected_pkg.package_id) {
            for (required_role, _) in &manifest.requires {
                if !by_role.contains_key(required_role) {
                    bail!(
                        "package {} requires role {required_role} but no provider is selected",
                        manifest.id
                    );
                }
            }
        }
    }

    selected.sort_by(|a, b| a.role.cmp(&b.role));
    Ok(Resolved {
        edition: flags.edition.clone(),
        channel: flags.channel.clone(),
        packages: selected,
        manifests,
        roles: config.roles,
        paths: config.paths,
    })
}

fn validate_contracts(config: &RootConfig, manifests: &BTreeMap<String, Manifest>) -> Result<()> {
    let mut registered: BTreeMap<&str, &str> = BTreeMap::new();
    for (contract_id, crate_name) in &config.contracts {
        let manifest = manifests
            .values()
            .find(|m| m.kind == "contract" && m.rust_crate() == Some(crate_name.as_str()))
            .with_context(|| {
                format!("contract {contract_id}: crate {crate_name} not found among packages")
            })?;
        if registered
            .insert(crate_name.as_str(), contract_id.as_str())
            .is_some()
        {
            bail!("contract crate {crate_name} registered twice");
        }
        if manifest.schema != 1 {
            bail!("contract {}: schema must be 1", manifest.id);
        }
    }
    for (role, def) in &config.roles {
        if !registered.contains_key(def.contract.as_str()) {
            bail!(
                "role {role}: contract {} not registered in [contracts]",
                def.contract
            );
        }
        if def.protected {
            // reserved for OEM checks
        }
    }
    Ok(())
}

fn validate(root: &Path) -> Result<()> {
    let mut flags = Flags {
        edition: "personal".to_owned(),
        profile: "default".to_owned(),
        channel: "official".to_owned(),
    };
    let config = load_root(root)?;
    let manifests = scan_manifests(root)?;
    validate_contracts(&config, &manifests)?;
    for edition in config
        .roles
        .values()
        .flat_map(|r| r.editions.iter())
        .collect::<BTreeSet<_>>()
    {
        flags.edition = (*edition).clone();
        let resolved = resolve(root, &flags)?;
        println!(
            "validate: edition={} profile={} channel={} packages={} roles={}",
            resolved.edition,
            flags.profile,
            resolved.channel,
            resolved.packages.len(),
            resolved.roles.len()
        );
    }
    println!("validate: ok ({} packages scanned)", manifests.len());
    Ok(())
}

fn plan(root: &Path, flags: &Flags) -> Result<()> {
    let resolved = resolve(root, flags)?;
    println!(
        "edition={} profile={} channel={}",
        resolved.edition, flags.profile, resolved.channel
    );
    for pkg in &resolved.packages {
        println!(
            "{:<28} -> {:<24} ({})",
            pkg.role, pkg.package_id, pkg.crate_name
        );
    }
    Ok(())
}

fn compose(root: &Path, flags: &Flags, check: bool) -> Result<()> {
    let resolved = resolve(root, flags)?;
    let mut files: BTreeMap<PathBuf, String> = BTreeMap::new();
    files.insert(
        root.join("crates/zk-composed/Cargo.toml"),
        compose_cargo_toml(root, &resolved)?,
    );
    files.insert(
        root.join("crates/zk-composed/src/lib.rs"),
        compose_lib(&resolved)?,
    );
    for app in ["desktop", "server"] {
        let template = root.join(format!("tools/zk/templates/app_{app}.Cargo.toml"));
        if template.is_file() {
            let content = fs::read_to_string(&template)
                .with_context(|| format!("read {}", template.display()))?;
            files.insert(root.join(format!("apps/{app}/Cargo.toml")), content);
        }
        files.insert(
            root.join(format!("apps/{app}/src/generated/packages.rs")),
            generated_packages_rs(&resolved),
        );
    }
    files.insert(
        root.join("shared/contracts/packages.json"),
        packages_json(&resolved)?,
    );
    files.insert(
        root.join("shared/contracts/roles.json"),
        roles_json(&resolved)?,
    );
    files.insert(
        root.join("docs/generated/PACKAGE-INDEX.md"),
        package_index_md(&resolved),
    );

    if check {
        let mut mismatches = Vec::new();
        for (path, expected) in &files {
            match fs::read_to_string(path) {
                Ok(actual) if actual == *expected => {}
                _ => mismatches.push(path.display().to_string()),
            }
        }
        if !mismatches.is_empty() {
            bail!("generated files differ: {}", mismatches.join(", "));
        }
        println!("compose: up to date ({} files)", files.len());
        return Ok(());
    }
    for (path, content) in &files {
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).with_context(|| format!("mkdir {}", parent.display()))?;
        }
        fs::write(path, content).with_context(|| format!("write {}", path.display()))?;
    }
    println!(
        "compose: wrote {} files (edition={}, channel={})",
        files.len(),
        resolved.edition,
        resolved.channel
    );
    Ok(())
}

fn rel_from_composed(root: &Path, dir: &Path) -> String {
    let rel = dir
        .strip_prefix(root)
        .map(|p| p.to_path_buf())
        .unwrap_or_else(|_| dir.to_path_buf());
    format!("../../{}", rel.display())
}

fn manifest_dir(root: &Path, manifest_id: &str, resolved: &Resolved) -> Result<PathBuf> {
    let manifest = resolved
        .manifests
        .get(manifest_id)
        .with_context(|| format!("manifest {manifest_id}"))?;
    let crate_name = manifest
        .rust_crate()
        .with_context(|| format!("manifest {manifest_id} no rust crate"))?;
    let packages_dir = root.join("packages");
    for group in fs::read_dir(&packages_dir)? {
        let group = group?;
        if !group.file_type()?.is_dir() {
            continue;
        }
        for entry in fs::read_dir(group.path())? {
            let entry = entry?;
            let manifest_path = entry.path().join("zk.toml");
            if !manifest_path.is_file() {
                continue;
            }
            let text = fs::read_to_string(&manifest_path)?;
            let parsed: Manifest = toml::from_str(&text)?;
            if parsed.id == manifest_id {
                let _ = crate_name;
                return Ok(entry.path());
            }
        }
    }
    bail!("dir not found for package {manifest_id}")
}

fn compose_cargo_toml(root: &Path, resolved: &Resolved) -> Result<String> {
    let mut deps: BTreeMap<String, String> = BTreeMap::new();
    for pkg in &resolved.packages {
        let dir = manifest_dir(root, &pkg.package_id, resolved)?;
        deps.insert(pkg.crate_name.clone(), rel_from_composed(root, &dir));
    }
    for manifest in resolved.manifests.values() {
        if manifest.kind == "contract" {
            if let Some(crate_name) = manifest.rust_crate() {
                let dir = manifest_dir(root, &manifest.id, resolved)?;
                deps.insert(crate_name.to_owned(), rel_from_composed(root, &dir));
            }
        }
    }
    let mut out = String::new();
    out.push_str("# @generated by zk compose -- do not edit\n");
    out.push_str("[package]\nname = \"zk-composed\"\nversion.workspace = true\nedition.workspace = true\nlicense.workspace = true\n\n[dependencies]\n");
    for (name, path) in &deps {
        out.push_str(&format!("{name} = {{ path = \"{path}\" }}\n"));
    }
    out.push_str("serde_json = { workspace = true }\n\n[lints]\nworkspace = true\n");
    Ok(out)
}

fn compose_lib(resolved: &Resolved) -> Result<String> {
    let mut tools = Vec::new();
    let mut llm: Option<&Selected> = None;
    let mut agent: Option<&Selected> = None;
    for pkg in &resolved.packages {
        if pkg.role.starts_with("tool.") {
            tools.push(pkg);
        } else if pkg.role == "llm.provider.default" {
            llm = Some(pkg);
        } else if pkg.role == "agent.loop" {
            agent = Some(pkg);
        } else {
            bail!(
                "compose: role {} has no glue rule in this M0 demo",
                pkg.role
            );
        }
    }
    let llm = llm.context("compose: llm.provider.default is required")?;
    let agent = agent.context("compose: agent.loop is required")?;
    let mut out = String::new();
    out.push_str("// @generated by zk compose -- do not edit\n#![forbid(unsafe_code)]\n\nuse std::sync::Arc;\n\n");
    out.push_str(&format!(
        "pub const EDITION: &str = \"{}\";\n",
        resolved.edition
    ));
    out.push_str("pub const PACKAGES: &[&str] = &[");
    for pkg in &resolved.packages {
        out.push_str(&format!("\"{}\",", pkg.package_id));
    }
    out.push_str("];\n\n");
    out.push_str("pub struct Runtime {\n    agent: Arc<dyn zk_contract_agent::Agent>,\n}\n\n");
    out.push_str("impl Runtime {\n    pub fn run(&self, input: &str) -> Result<serde_json::Value, String> {\n        let reply = self.agent.run(input).map_err(|e| e.to_string())?;\n        serde_json::to_value(reply).map_err(|e| e.to_string())\n    }\n\n    pub fn packages(&self) -> &'static [&'static str] {\n        PACKAGES\n    }\n}\n\n");
    out.push_str("pub fn build() -> Result<Runtime, String> {\n");
    out.push_str("    let mut tools: Vec<Arc<dyn zk_contract_tool::Tool>> = Vec::new();\n");
    for pkg in &tools {
        out.push_str(&format!(
            "    tools.push(Arc::new({}::tool()));\n",
            pkg.crate_name.replace('-', "_")
        ));
    }
    out.push_str(&format!(
        "    let llm: Arc<dyn zk_contract_llm::LlmProvider> = Arc::new({}::provider());\n",
        llm.crate_name.replace('-', "_")
    ));
    out.push_str(&format!(
        "    let agent: Arc<dyn zk_contract_agent::Agent> = Arc::new({}::agent(tools, llm));\n",
        agent.crate_name.replace('-', "_")
    ));
    out.push_str("    Ok(Runtime { agent })\n}\n");
    Ok(out)
}

