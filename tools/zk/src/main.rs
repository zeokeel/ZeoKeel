struct Manifest {
    schema: u32,
    id: String,
    kind: String,
    version: String,
    #[serde(default)]
    summary: String,
    #[serde(default)]
    role: Option<RoleDecl>,
    #[serde(default)]
    roles: Vec<RoleDecl>,
    #[serde(default)]
    facets: Facets,
    #[serde(default)]
    requires: BTreeMap<String, String>,
    #[serde(default)]
    ui: Option<UiSection>,
}

#[derive(Debug, Clone, Default, Deserialize)]
struct UiSection {
    #[serde(default)]
    contributions: Vec<UiContributionDecl>,
}

impl Manifest {
    fn role_decls(&self) -> Vec<&RoleDecl> {
        let mut out: Vec<&RoleDecl> = Vec::new();
        if let Some(role) = self.role.as_ref() {
            out.push(role);
        }
        out.extend(self.roles.iter());
        out
    }

    fn rust_crate(&self) -> Option<&str> {
        self.facets.rust.as_ref().map(|r| r.crate_name.as_str())
    }

    fn ui_contributions(&self) -> &[UiContributionDecl] {
        self.ui
            .as_ref()
            .map_or(&[], |ui| ui.contributions.as_slice())
    }
}

