    /// use alphabetic suffixes; otherwise the fixture itself contains clones).
    fn unique_block(prefix: &str) -> String {
        (0..40)
            .map(|index| {
                let name = word(index);
                format!("fn {prefix}_{name}() {{ let value = \"{prefix}\"; let _ = value; }}")
            })
            .collect::<Vec<_>>()
            .join("\n")
    }

