#[derive(Serialize)]
struct CapabilityJson<'a> {
    id: &'a str,
    path: &'a str,
}

fn scan_capabilities(root: &Path) -> Result<Vec<CapabilityJson<'static>>> {
    let mut out: Vec<CapabilityJson<'static>> = Vec::new();
    let mut roots: BTreeSet<PathBuf> = BTreeSet::new();
    // Every package crate can declare reusable capabilities (`packages/<group>/<pkg>/src`).
    let packages_dir = root.join("packages");
    if packages_dir.is_dir() {
        for group in fs::read_dir(&packages_dir)? {
            let group = group?;
            if !group.file_type()?.is_dir() {
                continue;
            }
            for entry in fs::read_dir(group.path())? {
                let entry = entry?;
                if !entry.file_type()?.is_dir() {
                    continue;
                }
                let src = entry.path().join("src");
                if src.is_dir() {
                    roots.insert(src);
                }
            }
        }
    }
    // Shared implementation libraries are not packages (docs/25 §2).
    let crates_dir = root.join("crates");
    if crates_dir.is_dir() {
        for entry in fs::read_dir(&crates_dir)? {
            let entry = entry?;
            let name = entry.file_name().to_string_lossy().to_string();
            if entry.file_type()?.is_dir() && name.starts_with("zk-kit-") {
                let src = entry.path().join("src");
                if src.is_dir() {
                    roots.insert(src);
                }
            }
        }
    }
    for dir in roots {
        walk_rs(&dir, root, &mut out)?;
    }
    out.sort_by(|a, b| a.id.cmp(b.id).then(a.path.cmp(b.path)));
    Ok(out)
}

/// Minimum capability-registration rule (docs/25 §27): every contract crate and every
/// `crates/zk-kit-*` crate must declare at least one `@capability` in its source.
/// Without this check `zk capability --check` could never detect an *unregistered*
/// public capability (it only compared the comments it found).
fn missing_capability_targets(
    root: &Path,
    manifests: &BTreeMap<String, Manifest>,
    caps: &[CapabilityJson<'static>],
) -> Result<Vec<String>> {
    let mut missing: BTreeSet<String> = BTreeSet::new();
    for manifest in manifests.values() {
        if manifest.kind != "contract" {
            continue;
        }
        let Some(crate_name) = manifest.rust_crate() else {
            continue;
        };
        let dir = find_package_dir(root, &manifest.id)?;
        let src_rel = dir
            .join("src")
            .strip_prefix(root)
            .map(|rel| rel.display().to_string())
            .unwrap_or_else(|_| dir.join("src").display().to_string());
        if !caps.iter().any(|cap| cap.path.starts_with(&src_rel)) {
            missing.insert(format!("package {} (crate {crate_name})", manifest.id));
        }
    }
    let crates_dir = root.join("crates");
    if crates_dir.is_dir() {
        for entry in fs::read_dir(&crates_dir)? {
            let entry = entry?;
            let name = entry.file_name().to_string_lossy().to_string();
            if !entry.file_type()?.is_dir() || !name.starts_with("zk-kit-") {
                continue;
            }
            let src = entry.path().join("src");
            if !src.is_dir() {
                continue;
            }
            let src_rel = src
                .strip_prefix(root)
                .map(|rel| rel.display().to_string())
                .unwrap_or_else(|_| src.display().to_string());
            if !caps.iter().any(|cap| cap.path.starts_with(&src_rel)) {
                missing.insert(format!("crate {name}"));
            }
        }
    }
    Ok(missing.into_iter().collect())
}

fn walk_rs(dir: &Path, root: &Path, out: &mut Vec<CapabilityJson<'static>>) -> Result<()> {
    if !dir.is_dir() {
        return Ok(());
    }
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        let path = entry.path();
        if entry.file_type()?.is_dir() {
            walk_rs(&path, root, out)?;
        } else if path.extension().and_then(|e| e.to_str()) == Some("rs") {
            let text = fs::read_to_string(&path)?;
            for line in text.lines() {
                if let Some(idx) = line.find("@capability ") {
                    let rest = match line.get(idx.saturating_add("@capability ".len())..) {
                        Some(v) => v,
                        None => continue,
                    };
                    let id: String = rest
                        .chars()
                        .take_while(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-'))
                        .collect();
                    if id.is_empty() {
                        continue;
                    }
                    let rel = path
                        .strip_prefix(root)
                        .unwrap_or(&path)
                        .display()
                        .to_string();
                    let id: &'static str = Box::leak(id.into_boxed_str());
                    let rel: &'static str = Box::leak(rel.into_boxed_str());
                    out.push(CapabilityJson { id, path: rel });
                }
            }
        }
    }
    Ok(())
}

fn capability(root: &Path, check: bool) -> Result<()> {
    let manifests = scan_manifests(root)?;
    let caps = scan_capabilities(root)?;
    let missing = missing_capability_targets(root, &manifests, &caps)?;
    if !missing.is_empty() {
        bail!(
            "capability index incomplete: contract/kit crates without a `@capability` declaration: {} \
             (rule: docs/25 §27)",
            missing.join(", ")
        );
    }
    let json = format!("{}\n", stable_json(&caps)?);
    let mut md = String::new();
    md.push_str("<!-- @generated by zk capability -- do not edit -->\n\n# Capability Index\n\n");
    md.push_str(&format!(
        "{} capabilities\n\n| id | path |\n| --- | --- |\n",
        caps.len()
    ));
    for cap in &caps {
        md.push_str(&format!("| `{}` | `{}` |\n", cap.id, cap.path));
    }
    let json_path = root.join("shared/contracts/capability-index.json");
    let md_path = root.join("docs/generated/CAPABILITY-INDEX.md");
    if check {
        for (path, expected) in [(&json_path, &json), (&md_path, &md)] {
            let actual = fs::read_to_string(path).unwrap_or_default();
            if actual != *expected {
                bail!("capability index differs: {}", path.display());
            }
        }
        println!("capability: up to date ({} entries)", caps.len());
        return Ok(());
    }
    if let Some(parent) = json_path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(&json_path, json)?;
    fs::write(&md_path, md)?;
    println!("capability: wrote {} entries", caps.len());
    Ok(())
}

fn find(root: &Path, keyword: &str) -> Result<()> {
    let path = root.join("shared/contracts/capability-index.json");
    let text = fs::read_to_string(&path)
        .with_context(|| format!("read {} (run zk capability first)", path.display()))?;
    let value: serde_json::Value = serde_json::from_str(&text)?;
    let mut found = 0usize;
    if let Some(items) = value.as_array() {
        for item in items {
            let id = item.get("id").and_then(|v| v.as_str()).unwrap_or("");
            let p = item.get("path").and_then(|v| v.as_str()).unwrap_or("");
            if id.contains(keyword) || p.contains(keyword) {
                println!("{id}\t{p}");
                found = found.saturating_add(1);
            }
        }
    }
    println!("find: {found} match(es) for {keyword}");
    Ok(())
}

fn lint(root: &Path, duplicates: bool, write_baseline: bool) -> Result<()> {
    let mut bad: Vec<String> = Vec::new();
    for base in ["packages", "apps", "crates", "tools"] {
        scan_forbidden_dirs(&root.join(base), root, &mut bad)?;
    }
    if !bad.is_empty() {
        bail!("forbidden shared-code locations: {}", bad.join(", "));
    }
    if !duplicates {
        println!("lint: ok (no forbidden utils/helpers/common dirs)");
        return Ok(());
    }
    let report = detect_duplicate_windows(root)?;
    let baseline_path = root.join("duplication-baseline.json");
    if write_baseline {
        let baseline = serde_json::json!({
            "schema": 1,
            "generated_by": "zk lint --duplicates --write-baseline",
            "files": report.files,
            "clone_windows": report.clone_windows,
        });
        fs::write(&baseline_path, format!("{}\n", stable_json(&baseline)?))?;
        println!(
            "lint: wrote baseline ({} files, {} clone windows)",
            report.files, report.clone_windows
        );
        return Ok(());
    }
    let baseline: Option<serde_json::Value> = if baseline_path.is_file() {
        Some(serde_json::from_str(&fs::read_to_string(&baseline_path)?)?)
    } else {
        None
    };
    let Some(baseline) = baseline else {
        bail!(
            "lint: {} missing; run `zk lint --duplicates --write-baseline` and commit it (docs/25 §4)",
            baseline_path.display()
        );
    };
    let schema = baseline
        .get("schema")
        .and_then(serde_json::Value::as_u64)
        .context("duplication-baseline.json: schema must be a number")?;
    if schema != 1 {
        bail!("duplication-baseline.json: unsupported schema {schema} (expected 1)");
    }
    let allowed = baseline
        .get("clone_windows")
        .and_then(serde_json::Value::as_u64)
        .context("duplication-baseline.json: clone_windows must be a number")?;
    if report.clone_windows > allowed {
        bail!(
            "lint: duplicate code ratchet exceeded: {} clone windows > baseline {} (docs/25 §4; refactor to reuse or get an ADR exception)",
            report.clone_windows,
            allowed
        );
    }
    println!(
        "lint: duplicates ok ({} files, {} clone windows <= baseline {})",
        report.files, report.clone_windows, allowed
    );
    Ok(())
}

/// Duplicate-window report (docs/25 §4 ratchet).
struct DuplicateReport {
    files: u64,
    clone_windows: u64,
}

struct Window {
    file: usize,
    start: usize,
    shingles: Vec<u64>,
}

const WINDOW_LINES: usize = 30;
const SHINGLE_LINES: usize = 7;
const NEAR_SIMILARITY_PERCENT: u64 = 70;

fn detect_duplicate_windows(root: &Path) -> Result<DuplicateReport> {
    let mut files = Vec::new();
    for base in ["packages", "crates", "apps", "tools"] {
        collect_rust_files(&root.join(base), &mut files)?;
    }
    let mut windows: Vec<Window> = Vec::new();
    let mut file_count = 0u64;
    for (file_index, file) in files.iter().enumerate() {
        let Ok(text) = fs::read_to_string(file) else {
            continue;
        };
        let lines: Vec<String> = text
            .lines()
            .map(normalize_rust_line)
            .filter(|line| !line.is_empty())
            .collect();
        if lines.len() < WINDOW_LINES {
            continue;
        }
        file_count = file_count.saturating_add(1);
        for start in 0..=lines.len().saturating_sub(WINDOW_LINES) {
            let window = lines
                .get(start..start.saturating_add(WINDOW_LINES))
                .context("duplicate window slice")?;
            let mut shingles = Vec::with_capacity(window.len().saturating_sub(SHINGLE_LINES));
            for offset in 0..=window.len().saturating_sub(SHINGLE_LINES) {
                let end = offset.saturating_add(SHINGLE_LINES);
                let text = window
                    .get(offset..end)
                    .context("duplicate shingle slice")?
                    .join("\u{1f}");
                shingles.push(fnv1a(text.as_bytes()));
            }
            shingles.sort_unstable();
            shingles.dedup();
            windows.push(Window {
                file: file_index,
                start,
                shingles,
            });
        }
    }
    // Candidate pairs share at least one shingle; then compare exact/near similarity.
    let mut buckets: BTreeMap<u64, Vec<usize>> = BTreeMap::new();
    for (index, window) in windows.iter().enumerate() {
        for hash in &window.shingles {
            let bucket = buckets.entry(*hash).or_default();
            if !bucket.contains(&index) {
                bucket.push(index);
            }
        }
    }
    let mut seen: BTreeSet<(usize, usize)> = BTreeSet::new();
    let mut clones = 0u64;
    for bucket in buckets.values() {
        if bucket.len() < 2 || bucket.len() > 256 {
            continue;
        }
        for left in 0..bucket.len() {
            for right in left.saturating_add(1)..bucket.len() {
                let Some(a) = bucket.get(left) else { continue };
                let Some(b) = bucket.get(right) else { continue };
                let pair = if a < b { (*a, *b) } else { (*b, *a) };
                if !seen.insert(pair) {
                    continue;
                }
                let Some(left_window) = windows.get(*a) else {
                    continue;
                };
                let Some(right_window) = windows.get(*b) else {
                    continue;
                };
                if left_window.file == right_window.file
                    && left_window.start.abs_diff(right_window.start) < WINDOW_LINES
                {
                    continue;
                }
                if jaccard_percent(&left_window.shingles, &right_window.shingles)
                    >= NEAR_SIMILARITY_PERCENT
                {
                    clones = clones.saturating_add(1);
                }
            }
        }
    }
    Ok(DuplicateReport {
        files: file_count,
        clone_windows: clones,
    })
}

fn jaccard_percent(left: &[u64], right: &[u64]) -> u64 {
    let mut left_index = 0usize;
    let mut right_index = 0usize;
    let mut intersection = 0u64;
    let mut union = 0u64;
    loop {
        match (left.get(left_index), right.get(right_index)) {
            (Some(left_value), Some(right_value)) => {
                union = union.saturating_add(1);
                if left_value == right_value {
                    intersection = intersection.saturating_add(1);
                    left_index = left_index.saturating_add(1);
                    right_index = right_index.saturating_add(1);
                } else if left_value < right_value {
                    left_index = left_index.saturating_add(1);
                } else {
                    right_index = right_index.saturating_add(1);
                }
            }
            (Some(_), None) => {
                union = union.saturating_add(1);
                left_index = left_index.saturating_add(1);
            }
            (None, Some(_)) => {
                union = union.saturating_add(1);
                right_index = right_index.saturating_add(1);
            }
            (None, None) => break,
        }
    }
    if union == 0 {
        0
    } else {
        intersection
            .saturating_mul(100)
            .checked_div(union)
            .unwrap_or(0)
    }
}

fn collect_rust_files(dir: &Path, out: &mut Vec<PathBuf>) -> Result<()> {
    if !dir.is_dir() {
        return Ok(());
    }
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().to_string();
        if entry.file_type()?.is_dir() {
            if matches!(
                name.as_str(),
                "target" | "node_modules" | "generated" | "tests" | "test-results"
            ) || name.starts_with('.')
            {
                continue;
            }
            collect_rust_files(&path, out)?;
        } else if name.ends_with(".rs") && !name.ends_with("_test.rs") {
            out.push(path);
        }
    }
    Ok(())
}

/// Normalize a Rust line for clone detection: drop comments, mask literals/numbers.
fn normalize_rust_line(line: &str) -> String {
    let trimmed = line.trim();
    if trimmed.is_empty() || trimmed.starts_with("//") {
        return String::new();
    }
    let mut out = String::with_capacity(trimmed.len());
    let mut in_string = false;
    let mut in_number = false;
    for ch in trimmed.chars() {
        if in_string {
            if ch == '"' {
                in_string = false;
                out.push('"');
            }
            continue;
        }
        if ch == '"' {
            in_string = true;
            out.push('"');
            out.push('S');
            out.push('"');
            continue;
        }
        if ch.is_ascii_digit() {
            if !in_number {
                out.push('N');
                in_number = true;
            }
            continue;
        }
        in_number = false;
        if ch.is_whitespace() {
            if !out.ends_with(' ') {
                out.push(' ');
            }
        } else {
            out.push(ch);
        }
    }
    out.trim().to_owned()
}

fn fnv1a(bytes: &[u8]) -> u64 {
    let mut hash = 0xcbf2_9ce4_8422_2325_u64;
    for byte in bytes {
        hash ^= u64::from(*byte);
        hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
    }
    hash
}

fn scan_forbidden_dirs(dir: &Path, root: &Path, bad: &mut Vec<String>) -> Result<()> {
    if !dir.is_dir() {
        return Ok(());
    }
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        let path = entry.path();
        if entry.file_type()?.is_dir() {
            let name = entry.file_name().to_string_lossy().to_string();
            let under_kit = path.starts_with(root.join("crates")) && name.starts_with("zk-kit-");
            if matches!(name.as_str(), "utils" | "helpers" | "common" | "misc") && !under_kit {
                bad.push(path.display().to_string());
            } else {
                scan_forbidden_dirs(&path, root, bad)?;
            }
        } else {
            if let Some(name) = path.file_name().and_then(|n| n.to_str()) {
                if matches!(name, "shared.ts" | "lib.ts") {
                    bad.push(path.display().to_string());
                }
            }
        }
    }
    Ok(())
}

