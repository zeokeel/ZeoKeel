/// Read the desktop app package version (the `X-ZeoKeel-Client` semver source).
fn desktop_version(root: &Path) -> Result<String> {
    let path = root.join("apps/desktop/Cargo.toml");
    let text = fs::read_to_string(&path).with_context(|| format!("read {}", path.display()))?;
    let value: toml::Value = toml::from_str(&text)?;
    let direct = value
        .get("package")
        .and_then(|package| package.get("version"))
        .and_then(toml::Value::as_str);
    if let Some(version) = direct {
        return Ok(version.to_owned());
    }
    // `apps/desktop` inherits the workspace version (`version.workspace = true`).
    let workspace_path = root.join("Cargo.toml");
    let workspace_text = fs::read_to_string(&workspace_path)
        .with_context(|| format!("read {}", workspace_path.display()))?;
    let workspace: toml::Value = toml::from_str(&workspace_text)?;
    workspace
        .get("workspace")
        .and_then(|workspace| workspace.get("package"))
        .and_then(|package| package.get("version"))
        .and_then(toml::Value::as_str)
        .map(ToOwned::to_owned)
        .context("workspace Cargo.toml: package.version missing")
}

