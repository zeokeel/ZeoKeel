#[derive(Serialize)]
struct PackageJson<'a> {
    id: &'a str,
    version: &'a str,
    kind: &'a str,
    roles: Vec<&'a str>,
}

#[derive(Serialize)]
struct RoleJson<'a> {
    package: &'a str,
    crate_name: &'a str,
    contract: &'a str,
    cardinality: &'a str,
}

fn packages_json(resolved: &Resolved) -> Result<String> {
    let mut out: Vec<PackageJson> = Vec::new();
    let mut seen = BTreeSet::new();
    for pkg in &resolved.packages {
        if !seen.insert(pkg.package_id.clone()) {
            continue;
        }
        if let Some(manifest) = resolved.manifests.get(&pkg.package_id) {
            out.push(PackageJson {
                id: &manifest.id,
                version: &manifest.version,
                kind: &manifest.kind,
                roles: manifest
                    .role_decls()
                    .iter()
                    .map(|r| r.name.as_str())
                    .collect(),
            });
        }
    }
    Ok(format!("{}\n", stable_json(&out)?))
}

fn roles_json(resolved: &Resolved) -> Result<String> {
    let mut map: BTreeMap<String, RoleJson> = BTreeMap::new();
    for pkg in &resolved.packages {
        map.insert(
            pkg.role.clone(),
            RoleJson {
                package: &pkg.package_id,
                crate_name: &pkg.crate_name,
                contract: &pkg.contract,
                cardinality: &pkg.cardinality,
            },
        );
    }
    Ok(format!("{}\n", stable_json(&map)?))
}

