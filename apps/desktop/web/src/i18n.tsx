const dictionaries: Record<Locale, Record<string, string>> = {
  "zh-CN": zhCN,
  "en-US": enUS,
};

/**
 * Dictionaries exported for the B13 parity/audit test (key sets, empty values,
 * placeholder parity). Components must keep using `translate`/`useUi().t`.
 */
export const messagesByLocale: Record<Locale, Record<string, string>> = dictionaries;

function format(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match: string, name: string) => {
    const value = vars[name];
    return value === undefined ? match : String(value);
  });
}

/** App infrastructure translator; packages receive it through UiProvider. */
export function translate(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const dictionary = dictionaries[locale];
  const fallback = dictionaries["zh-CN"];
  const template = dictionary[key] ?? fallback[key];
  if (template === undefined) {
    console.warn(`[zk] missing i18n key: ${key}`);
    return key;
  }
  return vars === undefined ? template : format(template, vars);
}
